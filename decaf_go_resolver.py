"""Construct exact field dispatch contracts from checked Goose extraction.

The generated instance retains the non-dispatch fields of an explicit base.
It does not construct GoGlobalContext, GoLocalContext, or PreSemantics, and it
does not prove that changing dispatch preserves a base semantics instance.
"""
import hashlib
import re

OPERATIONS = ("CmovznzU64", "Mul", "Square", "Add", "Sub", "Opp", "FromMontgomery",
              "ToMontgomery", "Nonzero", "Selectznz", "ToBytes", "FromBytes",
              "SetOne", "Msat", "DivstepPrecomp", "Divstep")
FIELD_NAMES = tuple(field + operation for field in ("Fq", "Fr") for operation in OPERATIONS)
BIT_NAMES = ("Add64", "Sub64", "Mul64")
TYPE_NAMES = ("FqUint1", "FrUint1", "FqInt1", "FrInt1")


def implementation_names(source, result_type):
    # Goose string literals can contain arbitrary byte values (math/bits tables).
    # Decode declaration text without losing or normalizing those source bytes.
    return re.findall(r"^Definition (\w+)ⁱᵐᵖˡ .* : " + re.escape(result_type) + r" :=",
                      source.decode("utf-8", errors="surrogateescape"), re.M)


def render(field_source, bits_source):
    if not isinstance(field_source, bytes) or not isinstance(bits_source, bytes):
        raise TypeError("resolver generation requires exact extraction bytes")
    names = implementation_names(field_source, "val")
    types = implementation_names(field_source, "go.type")
    bits = implementation_names(bits_source, "val")
    if len(names) != len(FIELD_NAMES) or set(names) != set(FIELD_NAMES):
        raise ValueError("extracted field function inventory differs from exact expected names")
    if len(types) != len(TYPE_NAMES) or set(types) != set(TYPE_NAMES):
        raise ValueError("extracted field named-type inventory differs from exact expected names")
    if any(bits.count(name) != 1 for name in BIT_NAMES):
        raise ValueError("missing or duplicated extracted word helper")
    entries = [("bits", name) for name in BIT_NAMES] + [("fiat", name) for name in FIELD_NAMES]
    lines = ["(* Generated by decaf_go_resolver.py; regenerate rather than edit. *)",
             "(* Field extraction SHA256: " + hashlib.sha256(field_source).hexdigest() + " *)",
             "(* Word extraction SHA256: " + hashlib.sha256(bits_source).hexdigest() + " *)",
             "From New.code.mizufinance_local.decaf Require Import fiat.",
             "From New.golang.theory Require Import auto.",
             "Section resolver.", "Context {ext : ffi_syntax} {go_gctx : GoGlobalContext}.",
             "Definition as_function (body : val) : func.t :=",
             "  match body with RecV f x e => func.mk f x e | _ => func.nil end.",
             "Definition field_function (name : go_string) (args : list go.type) : func.t :=",
             "  if decide (args = []) then"]
    for module, name in entries:
        lines.append(f"    if decide (name = {module}.{name}) then as_function {module}.{name}ⁱᵐᵖˡ else")
    lines += ["    func.nil else func.nil.", "Definition field_underlying (t : go.type) : go.type :="]
    for name in TYPE_NAMES:
        lines.append(f"  if decide (t = fiat.{name}) then fiat.{name}ⁱᵐᵖˡ else")
    lines += ["  t."]
    for name in TYPE_NAMES:
        lines += [f"Lemma underlying_{name} : field_underlying fiat.{name} = fiat.{name}ⁱᵐᵖˡ.",
                  "Proof. reflexivity. Qed."]
    for module, name in entries:
        lines += [f"Lemma resolve_{name} : field_function {module}.{name} [] = as_function {module}.{name}ⁱᵐᵖˡ.",
                  "Proof. reflexivity. Qed."]
    lines += ["(* Nil resolution is not itself a proved native panic or rejection. *)",
              "Lemma nonempty_type_arguments_nil name t ts : field_function name (t::ts) = func.nil.",
              "Proof. reflexivity. Qed.", "Context (base : GoSemanticsFunctions).",
              "Definition field_semantics : GoSemanticsFunctions :=",
              "  {| underlying := field_underlying;", "     functions := field_function;"]
    for field in ("global_addr", "methods", "method_set", "TypeRepr", "struct_field_ref", "array_index_ref",
                  "map_empty", "map_lookup", "map_insert", "map_delete", "is_map_domain", "is_map_pure", "map_default", "float_ops"):
        lines.append(f"     {field} := @{field} ext base;")
    lines[-1] = lines[-1][:-1] + " |}."
    lines += ["Context {go_lctx : GoLocalContext}."]
    for name in TYPE_NAMES:
        lines += [f"Lemma contract_{name} : @fiat.{name}_Assumptions ext go_gctx go_lctx field_semantics.",
                  "Proof. constructor. constructor. reflexivity. Qed."]
    lines += ["Context {func_encoding : go.IntoValUnfold func.t",
              "  (fun f => RecV (func.f f) (func.x f) (func.e f))}."]
    for module, name in entries:
        lines += [f"Lemma unfold_{name} : @FuncUnfold ext field_semantics go_gctx {module}.{name} [] {module}.{name}ⁱᵐᵖˡ.",
                  f"Proof. constructor. change (#(as_function {module}.{name}ⁱᵐᵖˡ) = {module}.{name}ⁱᵐᵖˡ).",
                  "  rewrite (go.into_val_unfold func.t). reflexivity. Qed."]
    # One audit root collects every contract without repeatedly auditing the
    # same large dispatch table once per projection.
    lines += ["Record FieldContracts : Prop := {"]
    for name in TYPE_NAMES:
        lines.append(f"  named_{name} : @fiat.{name}_Assumptions ext go_gctx go_lctx field_semantics;")
    for module, name in entries:
        lines.append(f"  body_{name} : @FuncUnfold ext field_semantics go_gctx {module}.{name} [] {module}.{name}ⁱᵐᵖˡ;")
    lines[-1] = lines[-1][:-1]
    lines += ["}.", "Lemma constructed_contracts : FieldContracts.", "Proof. constructor."]
    lines += [f"  - exact contract_{name}." for name in TYPE_NAMES]
    lines += [f"  - exact unfold_{name}." for _, name in entries]
    lines += ["Qed.", "End resolver."]
    return "\n".join(lines) + "\n"
