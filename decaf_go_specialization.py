"""Specialize the exact Goose field slice to explicit value encodings.

Body correspondence remains conditional on the old encoding interface. The
specialized bodies, syntax inventory, ranked calls and dispatcher do not require
GoGlobalContext. These are not native execution or termination proofs.
"""
import hashlib
import re

from decaf_go_resolver import BIT_NAMES, FIELD_NAMES, TYPE_NAMES, implementation_names

ENTRIES = tuple((m, n) for m, names in (("bits", BIT_NAMES), ("fiat", FIELD_NAMES)) for n in names)
GENERATED = ("GoFullSpecialization", "GoSpecializedClosure", "GoFieldCallRanks", "GoLiteralDispatch")
HANDWRITTEN = ("GoFieldControl", "GoFieldInteger", "GoFieldSyntax", "GoFieldClosure")
ROOTS = tuple(module + "." + prefix + name for module, prefix in (
    ("GoFullSpecialization", "specializes_"), ("GoSpecializedClosure", "closed_"),
    ("GoFieldCallRanks", "ranked_"), ("GoLiteralDispatch", "dispatch_")) for _, name in ENTRIES) + (
    "GoLiteralDispatch.resolve_own", "GoLiteralDispatch.name_injective",
    "GoLiteralDispatch.body_ranked", "GoLiteralDispatch.dispatch_sound") + tuple(
        "GoFieldControl." + name for name in (
            "execute_agrees", "return_agrees", "do_execute_agrees", "do_return_agrees", "seq_agrees", "do_agrees")) + (
    "GoFieldInteger.integer_roundtrip", "GoFieldInteger.integer_injective", "GoFieldInteger.integer_sound",
    "GoFieldSyntax.no_external_opcode", "GoFieldSyntax.no_external_value",
    "GoFieldClosure.foreign_calls_rejected", "GoFieldClosure.fork_rejected", "GoFieldClosure.unknown_resolver_rejected")


def declaration(source, name):
    found = re.findall(r"^Definition " + re.escape(name) + r" .*? :=.*?\.\n", source, re.M | re.S)
    if len(found) != 1:
        raise ValueError("missing or ambiguous Goose declaration: " + name)
    return found[0]


def explicit_body(body):
    body = body.replace(" {go_gctx : GoGlobalContext}", "")
    body = body.replace("exception_do", "literal_do").replace("bits.", "literal_bits.")
    for old, new in (("#()", "(encode Unit tt)"), ("#true", "(encode Bool true)"), ("#false", "(encode Bool false)")):
        body = body.replace(old, new)
    for width, representation in (("64", "Uint64"), ("8", "Uint8")):
        body = re.sub(r"#\(W" + width + r" ([0-9]+)\)",
                      r"(encode " + representation + r" (W" + width + r" \1))", body)
    body = re.sub(r"#([0-9]+)\b", r"(integer_literal \1)", body)
    if "#" in body or "GoGlobalContext" in body:
        raise ValueError("unhandled value representation in extracted field body")
    return body


def rank(module, name):
    return 0 if module == "bits" or name.endswith("CmovznzU64") else 1


NOTATIONS = '''Local Notation "e1 ;;; e2" := (literal_seq (Lam BAnon e2%E)%E e1%E) (at level 90, e2 at level 200) : expr_scope.
Local Notation "do: e" := (literal_do_execute e%E) (at level 90, e at level 85) : expr_scope.
Local Notation "return: e" := (literal_do_return e%E) (at level 90, e at level 85) : expr_scope.
'''


def render(field_bytes, bits_bytes):
    if not isinstance(field_bytes, bytes) or not isinstance(bits_bytes, bytes):
        raise TypeError("specialization requires exact extraction bytes")
    for actual, expected in ((implementation_names(field_bytes, "val"), FIELD_NAMES),
                             (implementation_names(field_bytes, "go.type"), TYPE_NAMES)):
        if len(actual) != len(expected) or set(actual) != set(expected):
            raise ValueError("field declaration inventory changed")
    bit_names = implementation_names(bits_bytes, "val")
    if any(bit_names.count(name) != 1 for name in BIT_NAMES):
        raise ValueError("missing or duplicated word helper")
    field = field_bytes.decode("utf-8", errors="surrogateescape")
    bits = bits_bytes.decode("utf-8", errors="surrogateescape")
    provenance = ("(* Generated by decaf_go_specialization.py; regenerate rather than edit. *)\n"
                  "(* Exact extraction SHA256: " + hashlib.sha256(field_bytes).hexdigest() + " " +
                  hashlib.sha256(bits_bytes).hexdigest() + " *)\n")
    source = provenance + "From New.code.mizufinance_local.decaf Require Import fiat.\nFrom New.golang Require Import defn.\n"
    source += "Require Import GoFieldEncoding GoFieldControl GoFieldInteger.\n"
    for module, text, names, types in (("bits", bits, BIT_NAMES, ()), ("fiat", field, FIELD_NAMES, TYPE_NAMES)):
        source += "Module literal_" + module + ".\n"
        for name in (*types, *names):
            source += declaration(text, name).replace(" {go_gctx : GoGlobalContext}", "").replace(" {ext : ffi_syntax}", "")
        source += NOTATIONS
        for name in names:
            source += explicit_body(declaration(text, name + "ⁱᵐᵖˡ"))
        source += "End literal_" + module + ".\n"
    source += "Section correspondence.\nContext {ext : ffi_syntax} {go_gctx : GoGlobalContext}.\n"
    for var, typ, representation in (("u", "unit", "Unit"), ("s", "go_string", "String"),
                                     ("w", "w64", "Uint64"), ("b", "w8", "Uint8"), ("B", "bool", "Bool")):
        source += f"Hypothesis H{var} : forall x : {typ}, (into_val x : val) = encode {representation} x.\n"
    source += "Hypothesis HZ : forall z : Z, (into_val z : val) = integer_literal z.\n"
    source += "Local Transparent " + " ".join("fiat." + name for name in TYPE_NAMES) + ".\n"
    # Put the control target first so its rejection cannot be confused with a
    # failure in another large body correspondence proof.
    proof_order = (("fiat", "FqAdd"),) + tuple(entry for entry in ENTRIES if entry != ("fiat", "FqAdd"))
    for module, name in proof_order:
        source += f"Lemma specializes_{name} : {module}.{name}ⁱᵐᵖˡ = literal_{module}.{name}ⁱᵐᵖˡ.\nProof.\n"
        source += f"  unfold {module}.{name}ⁱᵐᵖˡ, literal_{module}.{name}ⁱᵐᵖˡ.\n"
        source += "  repeat rewrite do_agrees. repeat rewrite (seq_agrees (Hu tt) Hs).\n"
        source += "  repeat rewrite (do_execute_agrees (Hu tt) Hs). repeat rewrite (do_return_agrees Hs).\n"
        source += "  repeat rewrite Hu. repeat rewrite Hw. repeat rewrite Hb. repeat rewrite HB. repeat rewrite HZ.\n"
        source += "  unfold " + ", ".join("fiat." + t for t in TYPE_NAMES) + ". reflexivity.\nQed.\n"
    source += "End correspondence.\n"
    result = {"GoFullSpecialization": source}
    header = provenance + "From New.golang Require Import defn.\nRequire Import GoFullSpecialization GoFieldSyntax GoFieldClosure.\n"
    closure = header + "Definition known_function (name : go_string) : bool := existsb (ByteString.eqb name) ["
    closure += ";".join("literal_" + m + "." + n for m, n in ENTRIES) + "].\n"
    for module, name in ENTRIES:
        closure += f"Lemma closed_{name} : @field_value field_syntax known_function (@literal_{module}.{name}ⁱᵐᵖˡ field_syntax) = true.\n"
        closure += "Proof. vm_compute. reflexivity. Qed.\n"
    result["GoSpecializedClosure"] = closure
    ranks = header + "Definition call_rank (name : go_string) : option nat :=\n"
    for value in (0, 1):
        names = ["literal_" + m + "." + n for m, n in ENTRIES if rank(m, n) == value]
        ranks += "if existsb (ByteString.eqb name) [" + ";".join(names) + f"] then Some {value}%nat else\n"
    ranks += "None.\nDefinition lower_rank caller (name : go_string) := match call_rank name with Some callee => Nat.ltb callee caller | None => false end.\n"
    for module, name in ENTRIES:
        ranks += f"Lemma ranked_{name} : @field_value field_syntax (lower_rank {rank(module, name)}) (@literal_{module}.{name}ⁱᵐᵖˡ field_syntax) = true.\n"
        ranks += "Proof. vm_compute. reflexivity. Qed.\n"
    result["GoFieldCallRanks"] = ranks
    source = header + "From Stdlib Require Import List.\nRequire Import GoFieldCallRanks.\n"
    source += "Inductive field_function_id := " + " | ".join("Id" + n for _, n in ENTRIES) + ".\n"
    source += "Definition all_ids : list field_function_id := [" + ";".join("Id" + n for _, n in ENTRIES) + "].\n"
    for label, typ, expression in (
        ("function_name", "go_string", lambda m, n: "literal_" + m + "." + n),
        ("function_body", "@val field_syntax", lambda m, n: "@literal_" + m + "." + n + "ⁱᵐᵖˡ field_syntax"),
        ("function_rank", "nat", lambda m, n: str(rank(m, n)) + "%nat")):
        source += f"Definition {label} id : {typ} := match id with\n"
        source += "\n".join("| Id" + n + " => " + expression(m, n) for m, n in ENTRIES) + "\nend.\n"
    source += '''Fixpoint resolve_in name ids : option field_function_id :=
  match ids with
  | [] => None
  | id :: rest => if decide (name = function_name id) then Some id else resolve_in name rest
  end.
Definition resolve name := resolve_in name all_ids.
Definition dispatch name := option_map function_body (resolve name).
Lemma resolve_in_sound name ids id : resolve_in name ids = Some id -> name = function_name id.
Proof.
  induction ids as [|head rest IH]; cbn; first discriminate.
  destruct (decide (name = function_name head)); [intros H; congruence|exact IH].
Qed.
Lemma resolve_own id : resolve (function_name id) = Some id.
Proof. destruct id; vm_compute; reflexivity. Qed.
Lemma name_injective a b : function_name a = function_name b -> a = b.
Proof. intros H. apply (f_equal resolve) in H. rewrite !resolve_own in H. now inversion H. Qed.
Lemma body_ranked id : @field_value field_syntax (lower_rank (function_rank id)) (function_body id) = true.
Proof. destruct id.
'''
    source += "\n".join("  - exact ranked_" + n + "." for _, n in ENTRIES) + "\nQed.\n"
    source += r'''Lemma dispatch_sound name body : dispatch name = Some body ->
  exists id, name = function_name id /\ body = function_body id /\
    @field_value field_syntax (lower_rank (function_rank id)) body = true.
Proof.
  unfold dispatch. destruct (resolve name) as [id|] eqn:Hid; cbn; try discriminate.
  intros H. inversion H; subst. exists id. split.
  - now apply resolve_in_sound in Hid.
  - split; [reflexivity|apply body_ranked].
Qed.
'''
    for module, name in ENTRIES:
        source += f"Lemma dispatch_{name} : dispatch literal_{module}.{name} = Some (@literal_{module}.{name}ⁱᵐᵖˡ field_syntax).\n"
        source += f"Proof. change (dispatch (function_name Id{name}) = Some (@literal_{module}.{name}ⁱᵐᵖˡ field_syntax)). unfold dispatch. rewrite resolve_own. reflexivity. Qed.\n"
    result["GoLiteralDispatch"] = source
    for output in result.values():
        output.encode("utf-8")  # Unsupported raw bytes in a reached body fail closed.
    return result
