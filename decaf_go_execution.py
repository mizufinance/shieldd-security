def render_shapes(field_bytes, bits_bytes):
    if not isinstance(field_bytes, bytes) or not isinstance(bits_bytes, bytes):
        raise TypeError("instruction inventory requires exact extraction bytes")
    source = ("(* Generated by decaf_go_execution.py; regenerate rather than edit. *)\n"
              "(* Exact extraction SHA256: " + hashlib.sha256(field_bytes).hexdigest() + " " +
              hashlib.sha256(bits_bytes).hexdigest() + " *)\n"
              "Require Import GoFieldInstructionShapes GoFullSpecialization.\n")
    for module, name in ENTRIES:
        source += (f"Lemma shape_{name} : shaped_value literal_{module}.{name}ⁱᵐᵖˡ = true.\n"
                   "Proof. vm_compute. reflexivity. Qed.\n")
    return source


def mutate(source, kind):
    if kind == "wrong-constant-range":
        old, new = "| U8 => 0 <= z < 2^8", "| U8 => 0 <= z < 2^9"
    elif kind == "wrong-pointer-conversion":
        old, new = "if decide (source = target) then scalar_conversion", "if true then scalar_conversion"
    elif kind == "wrong-word-add":
        old, new = "| GoPlus => Some (WordResult (word.add x y))", "| GoPlus => Some (WordResult (word.sub x y))"
    elif kind == "wrong-pointer-prefix":
        old, new = "Loc (loc_car l + Z.of_nat k) (loc_off l)", "Loc (loc_car l + Z.of_nat k + 1) (loc_off l)"
    elif kind == "wrong-tagged-relocation":
        old, new = "| _ => v end.", "| InjLV inner => InjLV (relocate_value k inner)\n  | _ => v end."
    elif kind == "wrong-pair-order":
        old = """    | Pair x y =>
      match evaluate fuel x h with
      | Some (x, h1) => match evaluate fuel y h1 with
        | Some (y, h2) => Some (PairV x y, h2) | None => None end"""
        new = """    | Pair x y =>
      match evaluate fuel y h with
      | Some (y, h1) => match evaluate fuel x h1 with
        | Some (x, h2) => Some (PairV x y, h2) | None => None end"""
    else:
        raise ValueError("unknown field execution control")
    if source.count(old) != 1 or new in source:
        raise ValueError("missing or ambiguous execution control anchor")
    return source.replace(old, new)
