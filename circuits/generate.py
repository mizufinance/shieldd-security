"""Generate a kernel-checked subset certificate from actual canonical Pari rows."""
import json
import re
from pathlib import Path
import sys

P = 52435875175126190479447740508185965837690552500527637822603658699938581184513

def generate(export):
    if not re.fullmatch(r'[0-9a-f]{64}', export.get('relation_digest', '')):
        raise ValueError('invalid relation digest')
    if export.get("scalar_encoding") != "canonical-big-endian-32" or int(export.get("modulus_minus_one", "0"), 16) + 1 != P:
        raise ValueError("unsupported scalar field or encoding")
    if export["public_inputs"] != 1 or export["committed_blocks"] != [1]:
        raise ValueError("unsupported layout")
    size = export["domain_size"]
    if not isinstance(size, int) or size <= 0 or size & (size - 1):
        raise ValueError("invalid padded domain")
    bits = export["bit_columns"]
    value = export["value_column"]
    if len(bits) != 128 or len(set(bits)) != 128 or value in bits:
        raise ValueError("invalid range column mapping")
    if value != 3 or export['commitment_column'] != 4 or bits != list(range(5, 133)) or size != 256:
        raise ValueError("unsupported or altered complete range column roles")
    def linear(terms):
        result = []
        previous = -1
        for column, encoded in terms:
            coefficient = int(encoded, 16)
            if len(encoded) != 64 or not 0 < coefficient < P or not previous < column < size:
                raise ValueError("noncanonical square row")
            previous = column
            signed = coefficient if coefficient <= P // 2 else coefficient - P
            result.append((column, signed))
        return result
    rows = [(linear(row["a"]), linear(row["b"])) for row in export["rows"]]
    if len(rows) > size:
        raise ValueError("too many rows")
    expected = [([(bit, 1)], [(bit, 1)]) for bit in bits]
    expected.append(([(value, -1)] + [(bit, 1 << i) for i, bit in enumerate(bits)], []))
    expected.append(([(1,1),(value,-1)], []))
    expected.append(([(2,1),(export["commitment_column"],-1)], []))
    # This actual compiler allocates the outlined constant after the last original witness.
    outline = max([value, export["commitment_column"], *bits]) + 1
    expected.append(([(0,1),(outline,-1)], []))
    if rows != expected:
        raise ValueError("unsupported or altered complete range component")
    if any(row not in rows for row in expected):
        raise ValueError("actual rows do not contain the proved range template")
    def show_linear(terms):
        return "[" + ", ".join(f"({column}, ({coefficient} : Int))" for column, coefficient in terms) + "]"
    rendered = ",\n  ".join("⟨" + show_linear(a) + ", " + show_linear(b) + "⟩" for a,b in rows)
    return f'''-- GENERATED by circuits/generate.py from actual compiled Pari rows. Do not edit.
-- Relation digest: {export['relation_digest']}
import ShielddSecurity.Rows
import Mathlib.Algebra.CharP.Defs
set_option maxHeartbeats 800000
set_option maxRecDepth 4096
namespace ShielddSecurity.RuntimeRange

def modulus : Nat := {P}
def rows : List Row := [
  {rendered}
]
def bitColumns : List Nat := {bits}
def valueColumn : Nat := {value}

theorem complete_rows : rows = bitColumns.map booleanRow ++
    [reconstructionRow valueColumn bitColumns, equalityRow 1 valueColumn,
     equalityRow 2 {export['commitment_column']}, equalityRow 0 {outline}] := by decide

theorem boolean_rows : bitColumns.all (fun i => decide (booleanRow i ∈ rows)) = true := by decide

theorem reconstruction_row : reconstructionRow valueColumn bitColumns ∈ rows := by decide

theorem public_link : equalityRow 1 valueColumn ∈ rows := by decide

/-- Scoped soundness of the exact emitted range component for every field assignment.
The field characteristic binds signed coefficient normalization to the runtime scalar field. -/
theorem range128_sound {{F : Type}} [Field F] [CharP F modulus]
    (rho : Nat → F) (satisfied : Satisfies rho rows) :
    ∃ n : Nat, n < 2^128 ∧ (n : F) = rho valueColumn := by
  have result := rows_range_sound rows valueColumn bitColumns boolean_rows reconstruction_row rho satisfied
  have length : bitColumns.length = 128 := rfl
  rw [length] at result
  exact result
theorem public_range128_sound {{F : Type}} [Field F] [CharP F modulus]
    (rho : Nat → F) (satisfied : Satisfies rho rows) :
    ∃ n : Nat, n < 2^128 ∧ (n : F) = rho 1 := by
  obtain ⟨n, bound, value⟩ := range128_sound rho satisfied
  exact ⟨n, bound, value.trans (equality_row_sound rows 1 valueColumn rho public_link satisfied).symm⟩

theorem emitted_range_completeness {{F : Type}} [Field F] [CharP F modulus]
    (rho : Nat → F)
    (bits : ∀ i ∈ bitColumns, Square (rho i) (rho i))
    (reconstruction : fieldBinary (bitColumns.map rho) = rho valueColumn)
    (publicCopy : rho 1 = rho valueColumn)
    (committedCopy : rho 2 = rho {export['commitment_column']})
    (constantCopy : rho 0 = rho {outline}) : Satisfies rho rows := by
  rw [complete_rows]
  exact range_rows_complete valueColumn {export['commitment_column']} {outline} bitColumns rho
    bits reconstruction publicCopy committedCopy constantCopy

/-- Every legal public integer and independently chosen commitment has an extension. -/
theorem input_completeness {{F : Type}} [Field F] [CharP F modulus]
    (n : Nat) (bound : n < 2^128) (commitment : F) :
    ∃ rho : Nat → F, rho 0 = 1 ∧ rho 1 = (n : F) ∧ rho 2 = commitment ∧ Satisfies rho rows := by
  let bits := encodeBits 128 n
  have length : bits.length = 128 := encodeBits_length 128 n
  have value : binary bits = n := encodeBits_value 128 n bound
  refine ⟨rangeAssignment bits commitment, ?_, ?_, ?_, ?_⟩
  · simp [rangeAssignment]
  · simp [rangeAssignment, value]
  · simp [rangeAssignment]
  · have columns : bitColumns = List.range' 5 128 := by decide
    rw [complete_rows, columns]
    simpa [length, valueColumn] using range_assignment_satisfies bits commitment
#print axioms range128_sound
#print axioms public_range128_sound
#print axioms emitted_range_completeness
#print axioms input_completeness
end ShielddSecurity.RuntimeRange
'''

if __name__ == "__main__":
    Path(sys.argv[2]).write_text(generate(json.loads(Path(sys.argv[1]).read_text())), encoding="utf-8")
