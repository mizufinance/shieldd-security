"""Fault sensitivity of complete compiler fixtures under arbitrary field assignments."""
from copy import deepcopy
import re

from controls import satisfies
from generate import P

if not __debug__:
    raise RuntimeError("compiler semantic controls require Python assertions enabled")


def complete_rows(fixture, expected, columns):
    """Check the complete relation, including input and constant links, before mutations."""
    if not re.fullmatch(r"[0-9a-f]{64}", fixture.get("relation_digest", "")):
        raise ValueError("invalid compiler fixture relation digest")
    if (fixture.get("domain_size"), fixture.get("public_inputs"), fixture.get("committed_blocks")) != (8, 1, [1]):
        raise ValueError("altered compiler fixture layout")
    if fixture.get("witness_columns") != columns:
        raise ValueError("altered compiler fixture witness roles")
    rows = []
    for row in fixture["rows"]:
        sides = []
        for side in ("a", "b"):
            terms = []
            previous = -1
            for column, encoded in row[side]:
                if type(column) is not int or not previous < column < 8 or not re.fullmatch(r"[0-9a-f]{64}", encoded):
                    raise ValueError("noncanonical compiler fixture row")
                coefficient = int(encoded, 16)
                if not 0 < coefficient < P:
                    raise ValueError("noncanonical compiler fixture coefficient")
                terms.append((column, coefficient if coefficient <= P // 2 else coefficient - P))
                previous = column
            sides.append(terms)
        rows.append(tuple(sides))
    if rows != expected:
        raise ValueError("altered complete compiler fixture rows")


def counterexample(fixture, assignment, removed, label):
    assert assignment[0] == 1, "the external leading-one convention must remain enforced"
    assert not satisfies(fixture, assignment), f"original accepted {label}"
    mutant = deepcopy(fixture)
    mutant["rows"].pop(removed)
    assert satisfies(mutant, assignment), f"weakened relation rejected {label}"
    return {"control": label, "relation_digest": fixture["relation_digest"],
            "removed_row": removed, "assignment": {str(k): str(v) for k, v in sorted(assignment.items())},
            "original_rejects": True, "weakened_accepts": True}


def check(export):
    if export.get("schema") != "shieldd.compiler-controls.v1":
        raise ValueError("unsupported compiler controls schema")
    if export.get("scalar_encoding") != "canonical-big-endian-32" or export.get("modulus_minus_one") != f"{P - 1:064x}":
        raise ValueError("unsupported compiler controls scalar")
    fixtures = export["fixtures"]
    if len(fixtures) != 5 or fixtures[0].get("kind") != "outlined_constant":
        raise ValueError("incomplete compiler fixture catalogue")
    constant = fixtures[0]
    complete_rows(constant, [
        ([(3, 1), (4, 11)], [(4, 324)]),
        ([(1, 1), (3, -1), (4, -11)], []),
        ([(2, 1), (3, -1)], []),
        ([(0, 1), (4, -1)], []),
    ], [3])
    for x in (7, P - 29):
        assignment = {0: 1, 1: (x + 11) % P, 2: x, 3: x, 4: 1}
        assert satisfies(constant, assignment), "valid outlined-constant fixture rejected"
    # All auxiliary/selected values are zero, but the external leading one stays
    # one. This satisfies every row except the actual outlined-one binding.
    bad = {0: 1, 1: 0, 2: 0, 3: 0, 4: 0}
    assert (bad[3] + 11) ** 2 % P != 324
    results = [counterexample(constant, bad, 3, "unbound outlined one admits source-unsatisfied x=0")]
    positive_assignments = 2
    variants = [(reverse, folded) for reverse in (False, True) for folded in (False, True)]
    for fixture, (reverse, folded) in zip(fixtures[1:], variants):
        if fixture.get("kind") != "deferred_squares" or fixture.get("reverse") is not reverse or fixture.get("folded") is not folded:
            raise ValueError("missing or altered deferred-square fixture variant")
        other, fused = (3, 4) if reverse else (4, 3)
        complete_rows(fixture, [
            ([(other, 1)], [(5, 1)]),
            ([(fused, 1)], [(5, 1)]),
            ([(1, 1), (3, -1)], []),
            ([(2, 1), (4, -1)], []),
            ([(0, 1), (6, -1)], []),
        ], [3, 4])
        for x, y in ((0, 0), (2, 2), (2, P - 2), (P - 1, 1)):
            assignment = {0: 1, 1: x, 2: y, 3: x, 4: y, 5: x * x % P, 6: 1}
            assert satisfies(fixture, assignment), "valid equal-square assignment rejected"
            positive_assignments += 1
        # Set the opposite square's witness to one and the fused side to zero.
        # The auxiliary square column is chosen adversarially, not generated by
        # the honest witness compiler. Removing either equality row must matter.
        x, y = (1, 0) if reverse else (0, 1)
        bad = {0: 1, 1: x, 2: y, 3: x, 4: y, 5: 0, 6: 1}
        assert x * x % P != y * y % P
        label = f"reverse={reverse},folded={folded}"
        results.append(counterexample(fixture, bad, 0, f"lost opposite-square materialization ({label})"))
        bad[5] = 1
        results.append(counterexample(fixture, bad, 1, f"lost fused-square equality ({label})"))
    return {"fixture_relations": 5, "positive_assignments": positive_assignments,
            "arbitrary_assignment_controls": results,
            "scope": "finite actual compiler fixtures and explicit field counterexamples; not whole-compiler verification"}
