from pathlib import Path
import argparse, hashlib, json, os

root = Path(__file__).resolve().parent
ap = argparse.ArgumentParser()
ap.add_argument('--output', type=Path, required=True)
args = ap.parse_args()
out = args.output.resolve()
assert not out.exists()
pending = out.with_name(out.name + '.pending')
pending.mkdir()
config = json.loads((root / 'parameters.json').read_bytes())
rows = json.loads((root / 'rows.json').read_bytes())
assert config['width'] == 252 and config['entries_per_leaf'] == 32
assert len(rows) == 2 * (config['width'] - 1)
modulus = 52435875175126190479447740508185965837690552500527637822603658699938581184513
sources = pending / 'source-root/ShielddSecurity'
sources.mkdir(parents=True)
inventory = {}

def linear(values, raw=False):
    values = sorted((200692 if col == 0 else col, value) for col, value in values)
    def coefficient(value):
        return '((p:Int)-1)' if raw and value == modulus-1 else str(value)
    return '[' + ','.join('(' + str(col) + ',' + coefficient(value) + ')' for col, value in values) + ']'

def emit(name, imports, body, names):
    text = '/- Generated by generate.py; edit the generator. -/\n'
    text += ''.join('import ShielddSecurity.' + item + '\n' for item in imports)
    text += 'set_option autoImplicit false\nset_option maxHeartbeats 900000\nset_option maxRecDepth 8192\nnoncomputable section\n'
    text += 'namespace ShielddSecurity.' + name + '\nopen Compiler CompilerArithmeticTransport41 CompilerAssertionBlock51 ComparisonCertificate101\n'
    text += body + '\nend ShielddSecurity.' + name + '\n'
    names = ['ShielddSecurity.' + name + '.' + item for item in names]
    text += ''.join('\nset_option pp.all true in\n#check @' + item + '\n#print axioms ' + item + '\n' for item in names)
    path = sources / (name + '.lean')
    path.write_text(text)
    inventory[name] = dict(sha256=hashlib.sha256(path.read_bytes()).hexdigest(), audits=names)

entries = []
before = [(config['bit_start'], -1), (200692, 1)]
for offset in range(config['width']-1):
    column = config['bit_start'] + offset + 1
    maximum = bool(config['maximum'] >> (offset+1) & 1)
    pivot = config['pivot_start'] + 2*offset
    auxiliary = pivot + 1
    after = [(column, -1), (pivot, 1), (200692, 1)] if maximum else [(pivot, 1)]
    pair = '[' + ','.join('⟨' + linear(row[0], True) + ',' + linear(row[1], True) + '⟩' for row in rows[2*offset:2*offset+2]) + ']'
    entry = '⟨' + str(column) + ',' + str(maximum).lower() + ',' + linear(before) + ',' + linear(after) + ',' + str(pivot) + ',' + str(auxiliary) + ',' + pair + '⟩'
    entries.append((entry, before, after))
    before = after

leaves = []
for index, start in enumerate(range(0, len(entries), 32)):
    name = 'ScalarCanonicalCapture387B' + str(index).zfill(2)
    leaves.append(name)
    selected = entries[start:start+32]
    arithmetic = config['arithmetic_start'] + 2*start
    count = 2*len(selected)
    body = 'def entries : List Entry := [' + ','.join(item[0] for item in selected) + ']\n'
    body += 'def initial : Linear := ' + linear(selected[0][1]) + '\n'
    body += 'def actualRows : List Row := entries.flatMap Entry.rows\n'
    body += 'noncomputable def productionCheck : Bool := chainCheck initial entries\n'
    body += 'theorem production_checked : productionCheck=true := by decide +kernel\n'
    body += 'noncomputable def rowCheck : Bool := CompilerRowSlice63.check CapturedFullArithmetic52.rowAt ' + str(arithmetic) + ' ' + str(count) + ' actualRows\n'
    body += 'theorem rows_checked : rowCheck=true := by decide +kernel\n'
    body += 'theorem output_exact : output initial entries=' + linear(selected[-1][2]) + ' := by rfl\n'
    body += 'variable {F : Type} [Field F] [CharP F p]\n'
    body += 'theorem semantic (rho : Nat → F) (one : rho copy=1) (arithmetic : SatisfiesAt rho CapturedFullArithmetic52.rowAt 177954) :\n'
    body += '    eval rho (output initial entries)=rawScan rho (eval rho initial) entries :=\n'
    body += '  chain_sound rho initial entries one production_checked (CompilerRowSlice63.of_full_satisfies CapturedFullArithmetic52.rowAt 177954 ' + str(arithmetic) + ' ' + str(count) + ' actualRows rows_checked (by decide) rho arithmetic)\n'
    emit(name, ['ComparisonCertificate101', 'CompilerRowSlice63', 'CapturedFullArithmetic52'], body,
         ['entries','initial','actualRows','productionCheck','production_checked','rowCheck','rows_checked','output_exact','semantic'])

assert len(leaves) == 8
def joined(items):
    return items[0] if len(items)==1 else items[0] + '++(' + joined(items[1:]) + ')'

body = ''.join('private abbrev E' + str(i) + ' := ' + name + '.entries\n' for i, name in enumerate(leaves))
body += 'def entries : List Entry := ' + joined(['E'+str(i) for i in range(8)]) + '\n'
body += 'def initial : Linear := ' + leaves[0] + '.initial\ndef actualRows : List Row := entries.flatMap Entry.rows\n'
body += 'noncomputable def productionCheck : Bool := chainCheck initial entries\n'
body += 'theorem production_checked : productionCheck=true := by\n'
body += '  have h7 := ' + leaves[7] + '.production_checked\n'
for i in reversed(range(7)):
    body += '  have h' + str(i) + ' : chainCheck ' + leaves[i] + '.initial (' + joined(['E'+str(j) for j in range(i,8)]) + ')=true := by\n'
    body += '    apply ComparisonComposition103.check_append\n    · exact ' + leaves[i] + '.production_checked\n'
    body += '    · rw [' + leaves[i] + '.output_exact]\n      exact h' + str(i+1) + '\n'
body += '  exact h0\n'
body += 'theorem output_exact : output initial entries=' + linear(entries[-1][2]) + ' := by rfl\n'
body += 'variable {F : Type} [Field F]\n'
body += 'private theorem sat_append (rho : Nat → F) (left right : List Row) (a : Satisfies rho left) (b : Satisfies rho right) : Satisfies rho (left++right) := by\n  intro row member\n  rcases List.mem_append.mp member with member|member\n  · exact a row member\n  · exact b row member\n'
body += 'theorem selected_satisfies (rho : Nat → F) (arithmetic : SatisfiesAt rho CapturedFullArithmetic52.rowAt 177954) : Satisfies rho actualRows := by\n'
for i, name in enumerate(leaves):
    start = i*32
    count = 2*min(32, len(entries)-start)
    body += '  have s' + str(i) + ' := CompilerRowSlice63.of_full_satisfies CapturedFullArithmetic52.rowAt 177954 ' + str(config['arithmetic_start']+2*start) + ' ' + str(count) + ' ' + name + '.actualRows ' + name + '.rows_checked (by decide) rho arithmetic\n'
body += '  change Satisfies rho (' + joined([name+'.actualRows' for name in leaves]) + ')\n'
for i in range(7):
    body += '  apply sat_append\n  · exact s' + str(i) + '\n'
body += '  exact s7\n'
body += 'theorem semantic [CharP F p] (rho : Nat → F) (one : rho copy=1) (arithmetic : SatisfiesAt rho CapturedFullArithmetic52.rowAt 177954) :\n    eval rho (output initial entries)=rawScan rho (eval rho initial) entries :=\n  chain_sound rho initial entries one production_checked (selected_satisfies rho arithmetic)\n'
emit('ScalarCanonicalCapture387', ['ComparisonComposition103'] + leaves, body,
     ['entries','initial','actualRows','productionCheck','production_checked','output_exact','selected_satisfies','semantic'])
(pending/'generation.json').write_text(json.dumps(inventory, sort_keys=True)+'\n')
os.replace(pending,out)
print(json.dumps(dict(modules=len(inventory), reports=sum(len(item['audits']) for item in inventory.values()))))
