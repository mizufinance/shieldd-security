from pathlib import Path
import argparse, hashlib, json, os, re

root=Path(__file__).resolve().parent
ap=argparse.ArgumentParser()
ap.add_argument('--output',type=Path,required=True)
args=ap.parse_args()
out=args.output.resolve()
assert not out.exists()
pending=out.with_name(out.name+'.pending')
pending.mkdir()
families=json.loads((root/'families.json').read_bytes())
assert len(families)==1
template=(root/'template.lean.in').read_text()
sources=pending/'source-root/ShielddSecurity'
sources.mkdir(parents=True)
inventory={}

for index,family in enumerate(families):
    name='BalanceBlindingCanonicalRows690F'+str(index).zfill(2)
    proof='BalanceBlindingCanonical689F'+str(index).zfill(2)
    block='CapturedAssertions50B'+str(family['position']//256).zfill(4)
    assert family['position']%256<255
    text=template.replace('IvkCanonicalRows389',name)
    text=text.replace('import ShielddSecurity.ScalarCanonicalNumeric388','import ShielddSecurity.'+proof)
    text=text.replace('CapturedAssertions50B0008',block)
    text='/- Generated by generate.py from the maintained assertion template. -/\nimport ShielddSecurity.'+block+'\n'+text
    replacements={203:family['position']%256,180205:177954+family['position'],2251:family['bit_start']+251,50706:family['pivot_start']+500}
    for before,after in replacements.items():
        text=re.sub(r'\b'+str(before)+r'\b',str(after),text)
    text=text.replace('rho (2000+index)=BinaryComparison100.bit (F:=F) (ScalarCanonicalNumeric388.bitAt n (2000+index))',
        'rho ('+str(family['bit_start'])+'+index)=BinaryComparison100.bit (F:=F) ((encodeBits 252 n)[index]?.getD false)')
    text=text.replace('ScalarCanonicalNumeric388.semantic rho n bound one arithmetic bits',proof+'.numeric rho n bound one arithmetic bits')
    assert 'ScalarCanonicalNumeric388.bitAt' not in text
    text=text.replace('\ndef ', '\nnoncomputable def ')
    path=sources/(name+'.lean')
    path.write_text(text)
    inventory[name]=dict(sha256=hashlib.sha256(path.read_bytes()).hexdigest(),audits=re.findall(r'#check @([A-Za-z0-9_.]+)',text))

(pending/'generation.json').write_text(json.dumps(inventory,sort_keys=True)+'\n')
os.replace(pending,out)
print(json.dumps(dict(modules=len(inventory),reports=sum(len(item['audits']) for item in inventory.values()))))
