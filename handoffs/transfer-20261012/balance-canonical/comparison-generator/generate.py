    body += 'theorem output_exact : rename 50706='+str(pivot+500)+' := by rfl\n'
    emit(defs,['CompilerColumnRenaming05','CompilerArithmeticTransport41','CompilerAssertionBlock51'],body,['rename','copy_exact','bit_exact','output_exact'])
    leaves = []
