    references = ['ScalarCanonicalCapture387B'+str(i).zfill(2)+'.actualRows' for i in range(8)]
    body += '  change Satisfies (fun column => rho ('+defs+'.rename column)) ('+joined(references)+')\n'
    for i in range(7):
        body += '  apply sat_append\n  · exact s'+str(i)+'\n'
