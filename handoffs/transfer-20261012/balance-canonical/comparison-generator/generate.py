    body = 'variable {F : Type} [Field F]\n'
    body += 'private theorem sat_append (rho : Nat → F) (left right : List Row) (a : Satisfies rho left) (b : Satisfies rho right) : Satisfies rho (left++right) := by\n'
    body += '  intro row member\n  rcases List.mem_append.mp member with member|member\n  · exact a row member\n  · exact b row member\n'
    body += 'theorem satisfies_template (rho : Nat → F) (arithmetic : SatisfiesAt rho CapturedFullArithmetic52.rowAt 177954) :\n'
    body += '    Satisfies (fun column => rho ('+defs+'.rename column)) ScalarCanonicalCapture387.actualRows := by\n'
