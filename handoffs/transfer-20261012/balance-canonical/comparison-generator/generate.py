        body += '  rw [CompilerRenamingChecks05.checked_rows '+defs+'.rename actualRows '+reference+'.actualRows rename_checked] at actual\n'
        body += '  exact (CompilerColumnRenaming05.satisfies_rows '+defs+'.rename rho '+reference+'.actualRows).mp actual\n'
