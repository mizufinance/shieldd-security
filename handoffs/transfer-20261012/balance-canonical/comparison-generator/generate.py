    body += '    simpa only [ScalarCanonicalNumeric388.bitAt,Nat.add_sub_cancel_left] using values index before\n'
    body += '  have result := ScalarCanonicalLocal392.semantic_rows (fun column => rho ('+defs+'.rename column)) n bound mappedOne (satisfies_template rho arithmetic) mappedBits\n'
