sources.mkdir(parents=True)
inventory = {}
modulus = 52435875175126190479447740508185965837690552500527637822603658699938581184513

def linear(values):
    values = sorted((200692 if col == 0 else col, value) for col, value in values)
    def coefficient(value):
        return '((p:Int)-1)' if value == modulus-1 else str(value)
    return '['+','.join('('+str(col)+','+coefficient(value)+')' for col,value in values)+']'

def emit(name, imports, body, names):
    text = '/- Generated by generate.py; edit the generator. -/\n'
    text += ''.join('import ShielddSecurity.'+item+'\n' for item in imports)
    text += 'set_option autoImplicit false\nset_option maxHeartbeats 900000\nset_option maxRecDepth 8192\nnoncomputable section\n'
    text += 'namespace ShielddSecurity.'+name+'\nopen Compiler CompilerArithmeticTransport41 CompilerAssertionBlock51\n'
    text += body+'\nend ShielddSecurity.'+name+'\n'
    names = ['ShielddSecurity.'+name+'.'+item for item in names]
    text += ''.join('\nset_option pp.all true in\n#check @'+item+'\n#print axioms '+item+'\n' for item in names)
    text=text.replace('\ndef ', '\nnoncomputable def ')
    path = sources/(name+'.lean')
    path.write_text(text)
    inventory[name] = dict(sha256=hashlib.sha256(path.read_bytes()).hexdigest(),audits=names)

def joined(items):
    return items[0] if len(items)==1 else items[0]+'++('+joined(items[1:])+')'

