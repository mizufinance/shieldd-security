        body = 'def actualRows : List Row := ['+','.join('⟨'+linear(row[0])+','+linear(row[1])+'⟩' for row in selected)+']\n'
        body += 'noncomputable def rowCheck : Bool := CompilerRowSlice63.check CapturedFullArithmetic52.rowAt '+str(arithmetic+2*start)+' '+str(count)+' actualRows\n'
        body += 'theorem rows_checked : rowCheck=true := by decide +kernel\n'
        body += 'theorem rename_checked : CompilerRenamingChecks05.checkRows '+defs+'.rename actualRows '+reference+'.actualRows=true := by decide +kernel\n'
        body += 'variable {F : Type} [Field F]\n'
        body += 'theorem satisfies_template (rho : Nat → F) (arithmetic : SatisfiesAt rho CapturedFullArithmetic52.rowAt 177954) :\n'
        body += '    Satisfies (fun column => rho ('+defs+'.rename column)) '+reference+'.actualRows := by\n'
