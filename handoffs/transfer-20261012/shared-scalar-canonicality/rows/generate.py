from pathlib import Path
import argparse, hashlib, json, os, re

root=Path(__file__).resolve().parent
ap=argparse.ArgumentParser()
ap.add_argument('--output',type=Path,required=True)
args=ap.parse_args()
out=args.output.resolve()
assert not out.exists()
pending=out.with_name(out.name+'.pending')
pending.mkdir()
families=json.loads((root/'families.json').read_bytes())
assert len(families)==9
template=(root/'template.lean.in').read_text()
sources=pending/'source-root/ShielddSecurity'
sources.mkdir(parents=True)
inventory={}

for index,family in enumerate(families):
    name='ScalarCanonicalRows395F'+str(index).zfill(2)
    proof='ScalarCanonicalRenames393F'+str(index).zfill(2)
    block='CapturedAssertions50B'+str(family['position']//256).zfill(4)
    assert family['position']%256<255
    text=template.replace('IvkCanonicalRows389',name)
    text=text.replace('import ShielddSecurity.ScalarCanonicalNumeric388','import ShielddSecurity.'+proof)
    text=text.replace('CapturedAssertions50B0008',block)
    text='/- Generated by generate.py from the maintained assertion template. -/\nimport ShielddSecurity.'+block+'\n'+text
    replacements={203:family['position']%256,180205:177954+family['position'],2251:family['bit_start']+251,50706:family['pivot_start']+500}
    for before,after in replacements.items():
        text=re.sub(r'\b'+str(before)+r'\b',str(after),text)
    text=text.replace('rho (2000+index)=BinaryComparison100.bit (F:=F) (ScalarCanonicalNumeric388.bitAt n (2000+index))',
        'rho ('+str(family['bit_start'])+'+index)=BinaryComparison100.bit (F:=F) ((encodeBits 252 n)[index]?.getD false)')
    text=text.replace('ScalarCanonicalNumeric388.semantic rho n bound one arithmetic bits',proof+'.numeric rho n bound one arithmetic bits')
    assert 'ScalarCanonicalNumeric388.bitAt' not in text
    path=sources/(name+'.lean')
    path.write_text(text)
    inventory[name]=dict(sha256=hashlib.sha256(path.read_bytes()).hexdigest(),audits=re.findall(r'#check @([A-Za-z0-9_.]+)',text))

names=['ScalarCanonicalRows395F'+str(i).zfill(2) for i in range(9)]
body='/- Generated by generate.py; edit the generator. -/\n'+''.join('import ShielddSecurity.'+name+'\n' for name in names)
body+='set_option autoImplicit false\nset_option maxHeartbeats 900000\nset_option maxRecDepth 8192\nnoncomputable section\nnamespace ShielddSecurity.ScalarCanonicalRows395\nopen Compiler CompilerArithmeticTransport41 CompilerAssertionBlock51\n'
body+='def bitStart (family : Fin 9) : Nat := '+str([f['bit_start'] for f in families]).replace(' ','')+'[family.val]!\n'
body+='def position (family : Fin 9) : Nat := '+str([f['position'] for f in families]).replace(' ','')+'[family.val]!\n'
body+='variable {F : Type} [Field F] [CharP F p]\n'
body+='theorem all_rows (rho : Nat → F) (numbers : Fin 9 → Nat) (bounded : ∀ family,numbers family<TransferCore.scalarOrder) (zero : rho 0=1) (one : rho copy=1)\n'
body+='    (arithmetic : SatisfiesAt rho CapturedFullArithmetic52.rowAt 177954)\n'
body+='    (bits : ∀ family,∀ index<252,rho (bitStart family+index)=BinaryComparison100.bit (F:=F) ((encodeBits 252 (numbers family))[index]?.getD false)) :\n'
body+='    ∀ family,SatisfiesAt rho (fun index => CapturedFullRelation58.rowAt (177954+position family+index)) 2 := by\n'
body+='  intro family\n  have cases : '+' ∨ '.join('family.val='+str(i) for i in range(9))+' := by omega\n'
body+='  rcases cases with '+'|'.join('h'+str(i) for i in range(9))+'\n'
for i,name in enumerate(names):
    body+='  · have same : family=⟨'+str(i)+',by decide⟩ := Fin.ext h'+str(i)+'\n    subst family\n'
    body+='    exact '+name+'.complete rho (numbers ⟨'+str(i)+',by decide⟩) (bounded ⟨'+str(i)+',by decide⟩) zero one arithmetic (bits ⟨'+str(i)+',by decide⟩)\n'
body+='end ShielddSecurity.ScalarCanonicalRows395\n'
owned=['ShielddSecurity.ScalarCanonicalRows395.'+name for name in ['bitStart','position','all_rows']]
body+=''.join('\nset_option pp.all true in\n#check @'+name+'\n#print axioms '+name+'\n' for name in owned)
path=sources/'ScalarCanonicalRows395.lean';path.write_text(body);inventory['ScalarCanonicalRows395']=dict(sha256=hashlib.sha256(path.read_bytes()).hexdigest(),audits=owned)

(pending/'generation.json').write_text(json.dumps(inventory,sort_keys=True)+'\n')
os.replace(pending,out)
print(json.dumps(dict(modules=len(inventory),reports=sum(len(item['audits']) for item in inventory.values()))))
