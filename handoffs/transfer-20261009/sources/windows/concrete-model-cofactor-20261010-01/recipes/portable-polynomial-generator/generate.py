"""Reproduce retained symbolic proposals, then emit complete certificates with only unused bindings removed.

The original SymPy generators propose coefficients; only Lean grants proof
credit. No generated Lean file is edited. Fresh outputs are published together
by one directory rename after both original byte-for-byte reproductions pass.
"""
import argparse
import ast
import hashlib
import json
import os
from pathlib import Path
import re
import sys
sys.dont_write_bytecode = True

ROOT = Path(__file__).resolve().parent
RECIPES = ROOT / 'inputs/recipes'
EXPECTED = {
    'secant': ('d972b22bc9457bec7fcc86e3401c9b907c212352561928b9eb59e4eea648f927',
               '2e3bc32cb908fbd220430846ad48b128066231583997f8c25c0d8bf73f8db22d'),
    'tangent': ('e806d130a080f1940f551075b9d666dff8c0d82086df34be22681f559cdf1ade',
                '6243b808dc516c18b57421e2459ef9d3a5b70b90a2baaf46352ddf86dc2e919b')}

def pin(path):
    path = Path(path)
    with path.open('rb') as f:
        sha = hashlib.file_digest(f, 'sha256').hexdigest()
    return {'path': str(path), 'bytes': path.stat().st_size, 'sha256': sha}

parser = argparse.ArgumentParser()
parser.add_argument('--sympy-path')
args = parser.parse_args()
if args.sympy_path:
    sys.path.insert(0, args.sympy_path)
import sympy
assert sympy.__version__ == '1.14.0'
assert not (ROOT / 'generated').exists()
pending = ROOT / '.generation.pending'
pending.mkdir(exist_ok=False)
inputs = []; bodies = {}; derivations = {}
for kind, (recipe_sha, source_sha) in EXPECTED.items():
    recipe = RECIPES / ('generate-edwards-' + kind + '-polynomials-20261009-01.py')
    source = ROOT / 'inputs/original-sources' / ('Edwards' + kind.title() + 'Polynomials01.lean')
    assert pin(recipe)['sha256'] == recipe_sha and pin(source)['sha256'] == source_sha
    inputs += [pin(recipe), pin(source)]
    text = recipe.read_text()
    # Run only the mathematical proposal/reduction prefix. Remove its old
    # dependency path and redirect the existence check to an unwritten fresh
    # path. Its old publication/record writes are excluded entirely.
    prefix = text[:text.index('\npending')]
    prefix, n = re.subn(r"(?m)^sys\.path\.insert\(0,\s*'C:/src/shieldd-transfer-handoffs/symbolic-exploration-deps01'\)\n", '', prefix)
    assert n == 1
    prefix, n = re.subn(r'(?m)^target\s*=\s*Path\([^\n]+\)', "target = Path(" + repr((ROOT / ('unwritten-' + kind + '.lean')).as_posix()) + ")", prefix)
    assert n == 1
    ast.parse(prefix)
    namespace = {'__file__': str(recipe)}
    exec(compile(prefix, str(recipe), 'exec'), namespace)
    body = namespace['body']
    assert hashlib.sha256(body.encode()).hexdigest() == source_sha
    bodies[kind] = body
    derivations[kind] = namespace['derivations']

removed = {}
def declaration_blocks(kind):
    body = bodies[kind]
    starts = list(re.finditer(r'(?m)^theorem ([A-Za-z0-9_]+) ', body))
    result = {}
    for i, match in enumerate(starts):
        end = starts[i + 1].start() if i + 1 < len(starts) else body.index('\nend ShielddSecurity.')
        block = body[match.start():end].rstrip()
        lines = block.splitlines()
        dropped = []
        # Remove only definitionally irrelevant bindings, walking backwards
        # so an unused binding cannot keep an otherwise unused dependency.
        for j in range(len(lines) - 1, -1, -1):
            found = re.fullmatch(r'\s+let ([A-Za-z0-9_]+) := .+', lines[j])
            if found and not re.search(r'\b' + re.escape(found[1]) + r'\b', '\n'.join(lines[j + 1:])):
                dropped.append(found[1]); lines.pop(j)
        removed[match[1]] = sorted(dropped)
        result[match[1]] = '\n'.join(lines)
    return result

secant = declaration_blocks('secant')
tangent = declaration_blocks('tangent')
assert removed['secant_x_polynomial'] == ['cross']
assert removed['secant_y_polynomial'] == []
assert removed['tangent_slope_polynomial'] == ['cross', 'delta', 'diagonal', 'h', 'm', 'p']
assert removed['tangent_x_polynomial'] == ['cross']
assert removed['tangent_y_polynomial'] == []

def emit(module, imports, declarations):
    text = '-- Generated by the retained-coefficient regeneration recipe; do not hand-edit.\n'
    text += ''.join('import ShielddSecurity.' + name + '\n' for name in imports)
    text += '\nset_option maxHeartbeats 300000\nset_option maxRecDepth 4096\n\n'
    text += 'namespace ShielddSecurity.' + module + '\nvariable {F : Type} [Field F]\n\n'
    text += '\n\n'.join(declarations) + '\n\nend ShielddSecurity.' + module + '\n'
    (pending / (module + '.lean')).write_text(text, encoding='utf-8', newline='\n')

emit('EdwardsSecantPolynomials01', ['EdwardsWeierstrassEquiv01'], list(secant.values()))
emit('EdwardsTangentPolynomials01', ['EdwardsWeierstrassEquiv01'], list(tangent.values()))
outputs = [pin(p) for p in sorted(pending.glob('*.lean'))]
assert len(outputs) == 2
assert sum(p.stat().st_size for p in ROOT.rglob('*') if p.is_file()) < 16 * 1024**2
os.replace(pending, ROOT / 'generated')
outputs = [pin(ROOT / 'generated' / Path(r['path']).name) for r in outputs]
review = {'generator': pin(Path(__file__)), 'inputs': inputs,
          'sympy_version': sympy.__version__, 'sympy_entrypoint': pin(sympy.__file__),
          'original_generators_reproduced_exactly': True,
          'derivations': derivations, 'removed_definitionally_unused_bindings': removed,
          'generated_sources': outputs, 'kernel_credit': 0,
          'scope': 'Atomic regenerated certificate source set. Both original certificate modules retained whole with their original theorem names. Coefficients and polynomial conclusions are preserved; unused lets eliminated by the generator. Await named Lean compilation; no runtime/control/certification credit.'}
(ROOT / 'generation-review.json').write_text(json.dumps(review, indent=2, sort_keys=True) + '\n')
print(json.dumps({'review': pin(ROOT / 'generation-review.json'), 'outputs': outputs, 'kernel_credit': 0}))
