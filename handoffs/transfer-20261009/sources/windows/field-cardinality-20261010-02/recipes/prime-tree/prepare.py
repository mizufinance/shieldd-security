"""Replay the original generator and prepare disjoint, finite named-module batches.

Generated proof bodies are unchanged and compared byte-for-byte to publication.
Only the audit generator appends ordered declaration type/axiom inspections.
"""
import ast
import hashlib
import json
from pathlib import Path
import re
import runpy
import shutil
import sys
ROOT = Path(__file__).resolve().parent
DIAG = ROOT.parent
PUB = Path('C:/src/shieldd-transfer-windows-publication-20261009')
PRIOR = DIAG / 'transfer-modular-power-field-20261010-01'
def pin(p):
    p = Path(p)
    with p.open('rb') as f: sha = hashlib.file_digest(f, 'sha256').hexdigest()
    return {'path': str(p), 'bytes': p.stat().st_size, 'sha256': sha}
batch = int(sys.argv[1]); assert 1 <= batch <= 5
candidate = PUB / 'handoffs/transfer-20261009/sources/parent/field-certificate-inputs01/candidate.json'
assert pin(candidate)['sha256'] == '20d3da8789fc847a4e5450c430321b52350e79f7533bcd43ff48695ffa4c862d'
original_recipe = PUB / 'handoffs/transfer-20261009/sources/windows/concrete-field-20261009-01/recipes/generate-field-certificate-tree-20261009-01.py'
if batch == 1:
    text = original_recipe.read_text()
    old = "out=Path('C:/src/shieldd-transfer-handoffs/field-certificate-tree-20261009-01/ShielddSecurity')"
    assert old in text
    text = text.replace(old, 'out=Path(' + repr(str(ROOT / 'raw-generated/ShielddSecurity')) + ')')
    ast.parse(text)
    replay = ROOT / 'replay_original_generator.py'
    replay.write_text(text, encoding='utf-8', newline='\n')
    runpy.run_path(str(replay), run_name='__main__')
    audited = ROOT / 'audited-generated'; audited.mkdir(exist_ok=False)
    source_records = []
    for n in range(1, 39):
        name = 'FieldPrimeNode%02d' % n
        source = ROOT / 'raw-generated/ShielddSecurity' / (name + '.lean')
        published = PUB / 'circuits/ShielddSecurity' / source.name
        assert source.read_bytes() == published.read_bytes(), name
        names = ['certificate', 'checked', 'prime']
        body = source.read_text() + '\n' + '\n'.join('set_option pp.all true in\n#check @ShielddSecurity.' + name + '.' + x + '\n#print axioms ShielddSecurity.' + name + '.' + x for x in names) + '\n'
        dest = audited / source.name; dest.write_text(body, encoding='utf-8', newline='\n')
        source_records.append({'module': name, 'original': pin(published), 'regenerated': pin(source), 'audit_generated': pin(dest)})
    lucas = PUB / 'circuits/ShielddSecurity/LucasCertificate.lean'
    body = lucas.read_text()
    names = re.findall(r'^(?:structure|def|theorem)\s+([A-Za-z0-9_.]+)', body, re.M)
    assert names == ['FactorPower', 'Certificate', 'FactorPower.check', 'Certificate.check', 'factor_power_sound', 'prime_divisor_member', 'certificate_sound']
    body += '\n' + '\n'.join('set_option pp.all true in\n#check @ShielddSecurity.LucasCertificate.' + n + '\n#print axioms ShielddSecurity.LucasCertificate.' + n for n in names) + '\n'
    dest = audited / lucas.name; dest.write_text(body, encoding='utf-8', newline='\n')
    source_records.insert(0, {'module': 'LucasCertificate', 'original': pin(lucas), 'audit_generated': pin(dest)})
    (ROOT / 'generation-review.json').write_text(json.dumps({'candidate': pin(candidate), 'original_recipe': pin(original_recipe), 'replay_recipe': pin(replay), 'audit_generator': pin(Path(__file__)), 'sources': source_records, 'scope': 'Exact 38 generated proof bodies reproduced from pinned candidate and unchanged original generator. Added ordered audits are generated by this recipe; zero kernel credit before named batch replay.'}, indent=2, sort_keys=True) + '\n')
review = json.loads((ROOT / 'generation-review.json').read_text())
for r in review['sources']:
    for k in ['original', 'regenerated', 'audit_generated']:
        if k in r: assert pin(r[k]['path']) == r[k]
task = DIAG / ('transfer-prime-tree-closed-20261010-%02d' % batch)
task.mkdir(exist_ok=False)
project = task / 'project/ShielddSecurity'; project.mkdir(parents=True)
plan = json.loads((PRIOR / 'plan.json').read_text())
base_records = list(plan['owned_imports'])
events = [json.loads(x) for x in (PRIOR / 'events.jsonl').read_text().splitlines()]
modular = next(e for e in events if e.get('module') == 'ModularPower' and e['event'] == 'attempt_finished')
assert modular['result']['status'] == 'passed'
base_records += modular['result']['objects']
history = []
for n in range(1, batch):
    previous = DIAG / ('transfer-prime-tree-closed-20261010-%02d' % n)
    p = json.loads((previous / 'plan.json').read_text())
    e = [json.loads(x) for x in (previous / 'events.jsonl').read_text().splitlines()]
    done = [x for x in e if x['event'] == 'attempt_finished']
    assert len(done) == len(p['targets']) and all(x['result']['status'] == 'passed' for x in done)
    base_records += [x for e in done for x in e['result']['objects']]
    history += [pin(previous / 'plan.json'), pin(previous / 'events.jsonl')] + [e['result']['stdout'] for e in done]
base = []
for record in base_records:
    assert pin(record['path']) == record
    dest = project / Path(record['path']).name
    assert not dest.exists()
    shutil.copyfile(record['path'], dest); base.append(pin(dest))
all_modules = ['LucasCertificate'] + ['FieldPrimeNode%02d' % n for n in range(1, 39)]
selected = all_modules[(batch - 1) * 8:batch * 8]
targets = []
for name in selected:
    record = next(r for r in review['sources'] if r['module'] == name)
    source = Path(record['audit_generated']['path']); dest = project / source.name
    shutil.copyfile(source, dest)
    text = source.read_text(); names = re.findall(r'^#print axioms ([A-Za-z0-9_.]+)', text, re.M)
    assert names == re.findall(r'^#check @([A-Za-z0-9_.]+)', text, re.M)
    targets.append({'module': name, 'source': pin(dest), 'predecessor_source': pin(source), 'imports': re.findall(r'^import\s+([A-Za-z0-9_.]+)', text, re.M), 'audit_names': names})
runner = task / 'execute_bounded.py'; text = (PRIOR / 'execute_bounded.py').read_text(); ast.parse(text)
runner.write_text(text, encoding='utf-8', newline='\n')
floor = DIAG / 'transfer-external-floor-complete-20261010-08/external-floor.json'
assert json.loads(floor.read_text())['admission_ready']
plan['external_floor'] = {**pin(floor), 'admission_ready': True}
plan['targets'] = targets; plan['owned_imports'] = base; plan['lean_path'][0] = str(task / 'project')
plan['lean_path'].insert(1, str(DIAG / 'transfer-external-package-overlay-20261010-03/modules'))
plan['pins'] += [pin(runner), pin(Path(__file__)), pin(ROOT / 'generation-review.json'), pin(floor), pin(original_recipe), pin(candidate), pin(PRIOR / 'events.jsonl'), modular['result']['stdout']] + base_records + base + history + [t['predecessor_source'] for t in targets]
plan['kind'] = 'EXACT_GENERATOR_REPLAY_LUCAS_PRIMALITY_TREE_BATCH'
plan['scope'] = 'One disjoint finite slice of the exact 38-node closed Lucas primality tree, with complete current external identity inventory and owned import closure. Only final node concludes concrete modulus prime. No curve cardinality, native, semantic negative control or full Transfer certification.'
plan['repairs'] = 'No proof body edits; original generator reproduced and compared with publication. Audits generated separately; max 8 named modules per batch, unchanged finite guards.'
(task / 'plan.json').write_text(json.dumps(plan, indent=2, sort_keys=True) + '\n')
(task / 'review.json').write_text(json.dumps({'plan': pin(task / 'plan.json'), 'runner': pin(runner), 'modules': selected, 'audits': sum(len(t['audit_names']) for t in targets), 'scope': plan['scope']}, indent=2) + '\n')
print(json.dumps({'plan': pin(task / 'plan.json'), 'modules': selected}))
