"""Root-only fresh child composer; actual parent inventory is mandatory.

The six sparse overlays are regenerated by retained pure hook functions and
compared byte-for-byte before any child is created. Existing EPK48/balance5
resources and modes are conserved by the complete parent inventory check.
"""
from pathlib import Path
import hashlib,json,shutil,sys


def sha(path):
    if not path.is_file() or path.is_symlink():raise ValueError('regular retained input required: '+str(path))
    h=hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda:stream.read(65536),b''):h.update(block)
    return h.hexdigest()


def inventory(root):
    result={}
    for path in sorted(root.rglob('*')):
        if path.is_symlink():raise ValueError('source inventory symlink: '+str(path))
        if path.is_file():result[path.relative_to(root).as_posix()]=sha(path)
    return result


def prepare(packet):
    packet=Path(packet);m=json.loads((packet/'manifest.json').read_bytes());p=packet.parent
    for rel,digest in m['files'].items():
        if sha(packet/rel)!=digest:raise ValueError('frozen blinding packet drift: '+rel)
    for input,digest in m['inputs'].items():
        portable=input.replace('\\','/')
        input_path=Path('/mnt/c/'+portable[3:]) if sys.platform!='win32' and portable.startswith('C:/') else Path(input)
        if sha(input_path)!=digest:raise ValueError('frozen ancestry drift: '+input)
    parent=Path(m['parent']);child=Path(m['child']);receipt=p/m['receipt']
    if (not parent.is_dir() or parent.is_symlink() or child.exists() or child.is_symlink() or receipt.exists() or receipt.is_symlink() or
        child.parent.resolve()!=parent.parent.resolve() or (parent/'.git').exists() or (parent/'target').exists()):
        raise ValueError('fresh isolated source child required')
    for guard in m['required_guards']:
        g=p/guard
        if (g/'exit.txt').read_text().strip()!='0' or (g/'wrapper-exit.txt').read_text().strip()!='0' or (g/'stop.txt').exists():
            raise ValueError('actual parent prerequisite guard incomplete: '+guard)
    if sha(Path(m['preserved_source11_binary']))!=m['source11_binary_sha256']:
        raise ValueError('source11 binary not preserved exactly before shared Cargo')
    before=inventory(parent)
    if before!=json.loads((p/m['actual_parent_inventory']).read_bytes()):
        raise ValueError('complete actual parent inventory changed')
    parent_result=json.loads((p/m['actual_parent_result']).read_bytes())
    if parent_result!=dict(status='source child only',variant='balance-sibling',pages=48,scopes=6,qualification=False,certification=False):
        raise ValueError('exact EPK48/balance5 parent stage result required')
    # This module is loaded from packet/lib; never import mutable producer origins.
    from . import balance_blinding_observer as observer
    prefix='crates/crypto/circuits/';generated={}
    for rel,fn in [('src/group.rs',observer.instrument_group),('src/balance.rs',observer.instrument_balance),('src/catalogue.rs',observer.instrument_catalogue)]:
        path=prefix+rel
        if before.get(path)!=m['changed'][path]['before']:raise ValueError('exact actual hook input changed: '+path)
        generated[path]=fn((parent/path).read_bytes())
    path=prefix+'examples/transfer-ownership-inspection.rs'
    if before.get(path)!=m['changed'][path]['before']:raise ValueError('complete actual exporter hook input changed')
    generated[path]=observer.instrument_exporter((parent/path).read_bytes(),(packet/'lib/integration/observers/balance_blinding_fixed_export.rs').read_bytes())
    for rel,resource in [('src/group/balance_blinding_fixed_inspection.rs','balance_blinding_fixed.rs'),('src/balance_blinding_fixed_catalogue.rs','balance_blinding_fixed_catalogue.rs')]:
        path=prefix+rel
        if path in before:raise ValueError('new blinding resource already exists')
        generated[path]=(packet/'lib/integration/observers'/resource).read_bytes()
    if set(generated)!=set(m['changed']) or len(generated)!=6:raise ValueError('exact six overlay ownership required')
    for path,data in generated.items():
        if hashlib.sha256(data).hexdigest()!=m['changed'][path]['after'] or data!=(packet/'overlay'/path).read_bytes():
            raise ValueError('pure hook composition differs from retained overlay: '+path)
    receipt.mkdir();shutil.copytree(parent,child)
    if inventory(child)!=before:raise ValueError('fresh source copy identity mismatch')
    for path,data in generated.items():
        destination=child/path;destination.parent.mkdir(parents=True,exist_ok=True);destination.write_bytes(data)
    after=dict(before);after.update({path:m['changed'][path]['after'] for path in generated})
    if inventory(child)!=after or inventory(parent)!=before:raise ValueError('source inventory closure mismatch')
    for name,value in [('parent-before.json',before),('parent-after.json',before),('child-after.json',after),('hooks-before-after.json',m['changed'])]:
        (receipt/name).write_text(json.dumps(value,sort_keys=True,indent=2)+'\n')
    with (receipt/'final-inventory.sha256').open('x') as stream:
        for path,digest in sorted(after.items()):stream.write(digest+'  '+path+'\n')
    (receipt/'source-only-result.json').write_text(json.dumps(dict(status='source child only',overlays=6,blinding_pages=8,
        epk_pages=48,balance_pages=5,qualification=False,certification=False))+'\n')
    for rel,digest in m['files'].items():
        if sha(packet/rel)!=digest:raise ValueError('retained source changed during staging')
    return after


def main():
    if len(sys.argv)!=2:raise ValueError('one immutable blinding packet path required')
    after=prepare(sys.argv[1]);print(json.dumps(dict(status='source child only',files=len(after),overlays=6,qualification=False)))


if __name__=='__main__':main()
