"""Data-only, isolated, closed-directory byte replay; performs no Lean build."""
import argparse,hashlib,json,os,subprocess,sys
from pathlib import Path

def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def regular(path):
    assert path.is_file() and not path.is_symlink(),f'not a regular non-symlink file: {path}'
def closed(folder,expected):
    assert folder.is_dir() and not folder.is_symlink(),'invalid maintained directory'
    found=list(folder.iterdir())
    assert {p.name for p in found}==set(expected),'maintained listing is not closed'
    for p in found:
        regular(p)
        assert sha(p)==expected[p.name],'maintained input changed: '+p.name
def main():
    parser=argparse.ArgumentParser()
    for name in ['inventory','maintained','descriptor','output','receipt']:
        parser.add_argument('--'+name,type=Path,required=True)
    args=parser.parse_args()
    result=dict(status='running',scope='Data-only byte regeneration; zero Lean/kernel runs',python=sys.version,
        python_flags=dict(isolated=sys.flags.isolated,no_site=sys.flags.no_site,dont_write_bytecode=sys.flags.dont_write_bytecode))
    assert not args.receipt.exists(),'receipt must be fresh'
    try:
        assert sys.flags.isolated and sys.flags.no_site and sys.flags.dont_write_bytecode,'requires -I -B -S'
        regular(args.inventory);regular(args.descriptor)
        inventory=json.loads(args.inventory.read_text());expected=inventory['maintained_files']
        closed(args.maintained,expected)
        recipe=Path(__file__);regular(recipe)
        assert recipe.resolve()==(args.maintained/'supported_verify_replay.py').resolve(),'executing recipe path is not inventoried'
        assert sha(recipe)==expected['supported_verify_replay.py'],'executing recipe hash mismatch'
        assert sha(args.descriptor)==inventory['descriptor_sha256'],'descriptor identity mismatch'
        assert not args.output.exists(),'output must be fresh'
        args.output.mkdir(parents=True)
        sources=args.output/'sources';sources.mkdir()
        metadata=args.output/'metadata';metadata.mkdir()
        observations=[]
        for name in inventory['generator_order']:
            closed(args.maintained,expected)
            assert sha(args.descriptor)==inventory['descriptor_sha256'],'descriptor changed'
            assert sha(args.inventory)==inventory_hash,'inventory changed'
            command=[sys.executable,'-I','-B','-S',str(args.maintained/name),
                '--descriptor',str(args.descriptor),'--output-dir',str(sources),'--metadata-dir',str(metadata)]
            child=subprocess.run(command,text=True,capture_output=True,timeout=60,
                env={k:v for k,v in os.environ.items() if not k.startswith('PYTHON')})
            (metadata/(name+'.stdout')).write_text(child.stdout)
            (metadata/(name+'.stderr')).write_text(child.stderr)
            assert child.returncode==0,'generator failed: '+name
            closed(args.maintained,expected)
            observations.append(dict(generator=name,command=command,exit=child.returncode))
        closed(args.maintained,expected)
        assert sha(args.inventory)==inventory_hash and sha(args.descriptor)==inventory['descriptor_sha256'],'input changed'
        files=list(sources.iterdir());assert {p.name for p in files}==set(inventory['generated_sources']),'generated output listing mismatch'
        reproduced={}
        for path in files:
            regular(path)
            assert sha(path)==inventory['generated_sources'][path.name]['sha256'],'generated bytes differ: '+path.name
            assert path.stat().st_size==inventory['generated_sources'][path.name]['bytes']
            reproduced[path.name]=dict(sha256=sha(path),bytes=path.stat().st_size)
        result.update(status='passed',inventory_sha256=inventory_hash,descriptor_sha256=sha(args.descriptor),
            maintained_files=expected,generated_sources=reproduced,modules=len(reproduced),bytes=sum(x['bytes'] for x in reproduced.values()),commands=observations)
    except Exception as error:
        result.update(status='refused',reason=str(error))
        raise
    finally:
        args.receipt.parent.mkdir(parents=True,exist_ok=True)
        args.receipt.write_text(json.dumps(result,indent=2)+'\n')

if __name__=='__main__':
    # Bind the exact inventory bytes before generators can execute.
    inv_index=sys.argv.index('--inventory')+1
    inventory_hash=sha(Path(sys.argv[inv_index]))
    main()
