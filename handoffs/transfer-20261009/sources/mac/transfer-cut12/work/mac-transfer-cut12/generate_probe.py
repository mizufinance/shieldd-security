"""Generate the admitted first-product probe from the qualified immutable cut."""
import argparse
import hashlib
import json
from pathlib import Path

STAGE = Path(__file__).resolve().parent
ROOT = STAGE.parents[1]
parser=argparse.ArgumentParser()
parser.add_argument('--descriptor',type=Path,default=ROOT/'outputs/mac-transfer-cut12/cut01.json')
parser.add_argument('--output-dir',type=Path,default=STAGE/'project/ShielddSecurity')
parser.add_argument('--metadata-dir',type=Path,default=ROOT/'outputs/mac-transfer-cut12')
args=parser.parse_args()
OUT=args.metadata_dir;OUT.mkdir(parents=True,exist_ok=True)
args.output_dir.mkdir(parents=True,exist_ok=True)
descriptor=args.descriptor
sha = lambda path: hashlib.sha256(path.read_bytes()).hexdigest()
assert sha(descriptor) == '1ae05048c9769e019be925dce1ee7694ebd74091775564c9b86fe7459925b604'
d = json.loads(descriptor.read_text())
assert d['runtime_sha'] == '844389ee069e1fb2e576708842d0b389b4d9a44a'
node = d['nodes'][1]
assert node['source_node'] == 129140 and node['operation'] == 'mul'
assert node['left'] == [1,7] and node['right'] == [2,129139]
assert node['certificate']['constructor'] == 'product'
assert node['certificate']['rows'] == [11058,11059]
rows = [d['indexed_original_rows'][i] for i in [0,1,4]]
assert [r['capture_index'] for r in rows] == [11058,11059,200769]
constant = d['constants'][0]['value']
def lc(terms):
    return '[' + ','.join(f'({column},{coefficient})' for column,coefficient in terms) + ']'
def audit(name):
    return f'\nset_option pp.all true in\n#check @ShielddSecurity.{name}\n#print axioms ShielddSecurity.{name}\n'
def theorem(namespace, name, body):
    return body + audit(namespace + '.' + name)
data_ns = 'TransferCut12ProbeData01'
proof_ns = 'TransferCut12ProductProbe01'
data = '''-- GENERATED by generate_probe.py; edit the maintained generator.
import ShielddSecurity.CompilerIndexed01
import ShielddSecurity.TransferPoseidonCall04Shared01
set_option autoImplicit false
set_option maxHeartbeats 900000
set_option maxRecDepth 8192
namespace ShielddSecurity.TransferCut12ProbeData01
open Compiler CompilerCompletion TransferPoseidonCall04Shared01
'''
data += f'def x : Linear := [(10,1)]\ndef y : Linear := [(0,{constant}),(23,1)]\n'
data += 'def z : Linear := [(33796,1)]\ndef auxiliary : Linear := [(33797,1)]\n'
data += 'def originalRows : Array Row := #[' + ',\n'.join('⟨'+lc(r['a'])+','+lc(r['b'])+'⟩' for r in rows) + ']\n'
data += '''def captureIndices : Array Nat := #[11058,11059,200769]
def inputTerms (input : Nat) : Linear := [(3+input,1)]
def earlier (index : Fin 2) : Expression := if index.val=0 then .linear x else .linear y
def hint : CompilerIndexed01.Hint 2 := .product 0 1 x y z auxiliary 0 1
def steps : List Step := [.product x y [] 33796 33797,copyStep]
def emittedRows : Array Row := (emitted steps).toArray
def mapping : Array Nat := #[0,1,2]
'''
for name, body in [
 ('product_checked','theorem product_checked : CompilerIndexed01.checkNode p copy originalRows inputTerms earlier hint=true := by decide +kernel\n'),
 ('order_checked','theorem order_checked : CompilerOrder.checkOrder [0,copy] [] steps=true := by decide +kernel\n'),
 ('coverage_checked','theorem coverage_checked : CompilerIndexed01.checkOriginalCoverage p copy originalRows emittedRows mapping=true := by decide +kernel\n'),
 ('probe_counts','theorem probe_counts : steps.length=2 ∧ originalRows.size=3 ∧ captureIndices.size=3 := by decide +kernel\n')]:
    data += theorem(data_ns,name,body)
data += f'end ShielddSecurity.{data_ns}\n'
proof = '''-- GENERATED by generate_probe.py; edit the maintained generator.
import ShielddSecurity.TransferCut12ProbeData01
set_option autoImplicit false
set_option maxHeartbeats 900000
set_option maxRecDepth 8192
namespace ShielddSecurity.TransferCut12ProductProbe01
open Compiler CompilerCompletion TransferPoseidonCall04Shared01 TransferCut12ProbeData01
'''
proof += theorem(proof_ns,'first_product_certificate','''theorem first_product_certificate : NodeCertificate p (unoutlineRows copy originalRows.toList)
    inputTerms earlier hint.node hint.output :=
  CompilerIndexed01.checkNode_sound p copy originalRows inputTerms earlier hint product_checked
''')
proof += theorem(proof_ns,'topological','''theorem topological : Topological [0,copy] [] steps :=
  CompilerOrder.checked_order [0,copy] [] steps order_checked
''')
proof += '''variable {F : Type} [Field F]
def completed (base : Nat → F) : Nat → F := run base steps
'''
proof += theorem(proof_ns,'legal','''theorem legal (base : Nat → F) : Legal base steps := by
  simp [steps,copyStep,Legal,Step.Legal]
''')
proof += theorem(proof_ns,'constructed_rows','''theorem constructed_rows [CharP F p] (base : Nat → F) (linked : base copy=base 0) :
    Satisfies (completed base) originalRows.toList := by
  have coverage := CompilerIndexed01.checkOriginalCoverage_sound p copy originalRows emittedRows mapping coverage_checked
  exact (original_rows_complete base steps [0,copy] originalRows.toList copy
    topological (legal base) (by simp) (by simp) linked coverage).1
''')
proof += theorem(proof_ns,'outside_preserved','''theorem outside_preserved (base : Nat → F) (column : Nat)
    (outside : column≠33796 ∧ column≠33797) : completed base column=base column := by
  apply PoseidonCompletion.run_outside base steps column
  simpa [PoseidonCompletion.writes,steps,Step.writes,copyStep] using outside
''')
proof += theorem(proof_ns,'original_inputs_preserved','''theorem original_inputs_preserved (base : Nat → F) (input : Nat) (bound : input<22735) :
    completed base (3+input)=base (3+input) :=
  outside_preserved base (3+input) (by constructor <;> omega)
''')
proof += theorem(proof_ns,'copy_preserved','''theorem copy_preserved (base : Nat → F) : completed base copy=base copy :=
  outside_preserved base copy (by decide)
''')
proof += f'end ShielddSecurity.{proof_ns}\n'
sources = {}
for name, content in [(data_ns,data),(proof_ns,proof)]:
    path=args.output_dir/f'{name}.lean'
    if path.exists() and path.read_text()!=content:
        historical=OUT/'source-history'/sha(path)/path.name
        historical.parent.mkdir(parents=True,exist_ok=True)
        assert not historical.exists() or historical.read_bytes()==path.read_bytes()
        historical.write_bytes(path.read_bytes())
    path.write_text(content)
    sources[name]={'sha256':sha(path),'bytes':path.stat().st_size}
metadata={'generator_sha256':sha(Path(__file__)),'descriptor_sha256':sha(descriptor),
          'sources':sources,'scope':'first product only; three selected actual rows, no whole-cut/kernel-join claim'}
index=1
while (OUT/f'probe-generation{index:02d}.json').exists(): index+=1
(OUT/f'probe-generation{index:02d}.json').write_text(json.dumps(metadata,indent=2)+'\n')
print(json.dumps(metadata))
