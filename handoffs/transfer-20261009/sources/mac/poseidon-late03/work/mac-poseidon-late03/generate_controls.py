"""Generate immutable-source negative controls from maintained templates."""
import hashlib,json,os,re
from pathlib import Path
S=Path(__file__).resolve().parent;R=S.parents[1];O=R/'outputs/mac-poseidon-late03';P=S/'project/ShielddSecurity';h=lambda b:hashlib.sha256(b).hexdigest();records=[]
for template,module in [('direct-controls-data-template.lean.txt','TransferPoseidonLate03ControlsData01'),('direct-controls-template.lean.txt','TransferPoseidonLate03Controls01')]:
 source=(S/template).read_text();text=source;names=re.findall(r'^theorem (\w+)',text,re.M)
 for name in reversed(names):
  start=re.search(r'^theorem '+name+r'\b',text,re.M).start();nxt=re.search(r'^(theorem|end)\b',text[start+1:],re.M);at=start+1+nxt.start()
  text=text[:at]+f'set_option pp.all true in\n#check @ShielddSecurity.{module}.{name}\n#print axioms ShielddSecurity.{module}.{name}\n\n'+text[at:]
 b=('-- GENERATED by generate_controls.py; edit '+template+'.\n'+text).encode();p=P/(module+'.lean')
 if p.exists() and p.read_bytes()!=b:
  old=p.read_bytes();hist=O/'source-history';hist.mkdir(exist_ok=True);(hist/(module+'-'+h(old)+'.lean')).write_bytes(old)
 tmp=p.with_suffix('.tmp');tmp.write_bytes(b);os.replace(tmp,p);records.append(dict(module=module,sha256=h(b),bytes=len(b),template=template,template_sha256=h(source.encode()),audits=names))
i=1
while (O/f'controls-generation{i:02d}.json').exists():i+=1
receipt=dict(generator_sha256=h(Path(__file__).read_bytes()),sources=records)
(O/f'controls-generation{i:02d}.json').write_text(json.dumps(receipt,indent=2)+'\n');print(json.dumps(receipt))
