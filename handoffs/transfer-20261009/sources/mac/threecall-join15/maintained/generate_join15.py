def require(ok, reason):
    if not ok: raise RuntimeError(reason)
"""Source-only exact five-module emission. Never invokes a theorem prover."""
import argparse, hashlib, json, os, re, sys
from pathlib import Path
require(sys.flags.isolated and sys.flags.dont_write_bytecode and sys.flags.no_site, 'closed generator guard')
require(__debug__, 'closed generator guard')
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()

def closed(directory, inventory):
    require(directory.is_dir() and (not directory.is_symlink()), 'closed generator guard')
    require({p.name for p in directory.iterdir()} == set(inventory), 'closed generator guard')
    for name, e in inventory.items():
        p = directory / name
        require(p.is_file() and (not p.is_symlink()), 'closed generator guard')
        require(sha(p) == e['sha256'] and p.stat().st_size == e['bytes'], 'closed generator guard')

def record(p, e):
    require(p.is_file() and (not p.is_symlink()), 'closed generator guard')
    require(sha(p) == e['sha256'] and p.stat().st_size == e['bytes'], 'closed generator guard')

def literal(terms):
    require(all((type(c) is int and c >= 0 and (type(k) is int) for c, k in terms)), 'closed generator guard')
    return '[' + ', '.join(('(' + str(c) + ',' + str(k) + ')' for c, k in terms)) + ']'

def main():
    ap = argparse.ArgumentParser()
    for n in ['input', 'input-sha256', 'inventory', 'inventory-sha256', 'output']:
        ap.add_argument('--' + n, required=True)
    a = ap.parse_args()
    mi = Path(a.inventory)
    inp = Path(a.input)
    out = Path(a.output)
    require(sha(mi) == a.inventory_sha256 and sha(inp) == a.input_sha256, 'closed generator guard')
    inventory = json.loads(mi.read_bytes())
    own = Path(__file__).resolve()
    closed(own.parent, inventory)
    require(inventory[own.name]['sha256'] == sha(own), 'closed generator guard')
    data = json.loads(inp.read_bytes())
    require(data['schema'] == 'join15-source-input01' and data['proof_credit'] == 0, 'closed generator guard')
    for p, e in data['required_records'].items():
        record(Path(p), e)
    aliases = []
    old = Path(data['component_controls_source']).read_text()
    for name in data['component_control_names']:
        matches = re.findall('^theorem ' + re.escape(name) + '\\s*:[^\\n]*?(?= :=)', old, re.M)
        require(len(matches) == 1, name)
        statement = matches[0].replace('theorem ' + name + ' :', 'theorem component_' + name + ' :', 1)
        aliases.append(statement + ' := TransferPoseidonCall14Controls01.' + name + '\n')
    require(len(aliases) == 13, 'closed generator guard')
    substitutions = {'@@INPUT0@@': literal(data['raw_lc_literals']['16577']), '@@INPUT1@@': literal(data['raw_lc_literals']['21951']), '@@RESULT@@': literal(data['raw_lc_literals']['23593']), '@@COMPONENT_CONTROL_ALIASES@@': ''.join(aliases)}
    require(not out.exists(), 'closed generator guard')
    out.parent.mkdir(parents=True, exist_ok=True)
    temp = out.with_name(out.name + '.emitting')
    require(not temp.exists(), 'closed generator guard')
    temp.mkdir()
    (temp / 'ShielddSecurity').mkdir()
    sources = {}
    for short, spec in data['modules'].items():
        body = (own.parent / (short + '.lean.txt')).read_text()
        for token, value in substitutions.items():
            expected = data['placeholder_counts'][short].get(token, 0)
            require(body.count(token) == expected, (short, token))
            body = body.replace(token, value)
        require('@@' not in body, 'closed generator guard')
        module = 'TransferPoseidonThreeCallJoin15' + short
        text = '-- GENERATED by generate_join15.py; edit the maintained template and regenerate.\n'
        text += ''.join(('import ' + n + '\n' for n in spec['imports']))
        text += 'set_option autoImplicit false\nset_option maxHeartbeats 900000\nset_option maxRecDepth 8192\n'
        text += 'namespace ShielddSecurity.' + module + '\n' + spec['opens'] + '\n' + body
        text += 'end ShielddSecurity.' + module + '\n'
        names = re.findall('^(?:def|theorem) (\\w+)\\b', body, re.M)
        require(len(names) == len(set(names)) and names == spec['declarations'], (short, names))
        for name in names:
            qualified = 'ShielddSecurity.' + module + '.' + name
            text += '\nset_option pp.all true in\n#check @' + qualified + '\n#print axioms ' + qualified + '\n'
        p = temp / 'ShielddSecurity' / (module + '.lean')
        p.write_text(text)
        require(p.stat().st_size <= 262144, 'closed generator guard')
        sources[module] = {'sha256': sha(p), 'bytes': p.stat().st_size, 'expected_signature_names': ['ShielddSecurity.' + module + '.' + n for n in names], 'expected_axiom_names': ['ShielddSecurity.' + module + '.' + n for n in names], 'imports': spec['imports'], 'kernel_status': 'UNRUN'}
    require(len(sources) == 5, 'closed generator guard')
    closed(own.parent, inventory)
    for p, e in data['required_records'].items():
        record(Path(p), e)
    (temp / 'emission01.json').write_text(json.dumps({'classification': 'source-only ZERO formal credit', 'input_sha256': a.input_sha256, 'maintained_inventory_sha256': a.inventory_sha256, 'modules': sources}, indent=2) + '\n')
    os.rename(temp, out)
    print(json.dumps({'output': str(out), 'sources': 5, 'bytes': sum((v['bytes'] for v in sources.values())), 'planned_audits': sum((len(v['expected_axiom_names']) for v in sources.values())), 'kernel_runs': 0}))
if __name__ == '__main__':
    main()
