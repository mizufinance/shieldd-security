"""Emit one fully qualified audit per unique theorem in the pilot import closure."""
import json,re
from pathlib import Path

STAGE=Path(__file__).resolve().parent
ROOT=STAGE.parents[1]
OUT=ROOT/'outputs/mac-transfer-pilot01'
PROJECT=STAGE/'project'
packet=json.loads((OUT/'input-packet01.json').read_text())['packet']
modules=packet['topological_import_order']+['TransferCompilerPilotData01','TransferCompilerPilot01']
roster=[]; occurrences=[]
for module in modules:
    namespace=''
    for line in (PROJECT/'ShielddSecurity'/f'{module}.lean').read_text().splitlines():
        if line.startswith('namespace '):namespace=line.split()[1]
        if re.match(r'^end(?: |$)',line):namespace=''
        match=re.match(r'^#print axioms (\S+)',line)
        if match:
            name=match.group(1)
            if not name.startswith('ShielddSecurity.'):name=namespace+'.'+name
            occurrences.append(dict(source=module,theorem=name))
            if name not in roster:roster.append(name)
assert len(roster)==77 and len(occurrences)==78
text=['-- GENERATED by generate_audit.py; do not hand-edit.',
      'import ShielddSecurity.TransferCompilerPilot01','set_option maxHeartbeats 200000']
for theorem in roster:
    text+=['set_option pp.all true in','#check @'+theorem,'#print axioms '+theorem]
(PROJECT/'ShielddSecurity/TransferCompilerPilotAudit01.lean').write_text('\n'.join(text)+'\n')
(OUT/'audit-roster01.json').write_text(json.dumps(dict(unique_theorems=roster,
    source_occurrences=occurrences,duplicate_imported_audit='ShielddSecurity.boolean_sound'),indent=2)+'\n')
(PROJECT/'ShielddSecurity/TransferCompilerPilotImportFloor.lean').write_text(
    '-- GENERATED by generate_audit.py; do not hand-edit.\n'
    'import ShielddSecurity.TransferCompilerPilotData01\n'
    'set_option maxHeartbeats 200000\n'
    'namespace ShielddSecurity.TransferCompilerPilotImportFloor\n'
    'theorem measured : True := True.intro\n'
    'end ShielddSecurity.TransferCompilerPilotImportFloor\n'
    'set_option pp.all true in\n'
    '#check @ShielddSecurity.TransferCompilerPilotImportFloor.measured\n'
    '#print axioms ShielddSecurity.TransferCompilerPilotImportFloor.measured\n')
print(json.dumps(dict(unique_names=len(roster),source_occurrences=len(occurrences))))
