"""Generate a finite concrete compiler pilot from qualified immutable M18 data."""
import hashlib,json,sqlite3
from pathlib import Path

STAGE=Path(__file__).resolve().parent
ROOT=STAGE.parents[1]
PROJECT=STAGE/'project'
OUT=ROOT/'outputs/mac-transfer-pilot01'
DB=ROOT/'work/parent-full-program/capture/lowering-resume01.sqlite'
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
def streamed_sha(path):
    value=hashlib.sha256()
    with path.open('rb') as stream:
        while raw:=stream.read(1024**2):value.update(raw)
    return value.hexdigest()
provenance=json.loads((OUT/'provenance-successor01.json').read_text())
assert provenance['status']=='passed' and provenance['runtime_sha']=='844389ee069e1fb2e576708842d0b389b4d9a44a'
for name,identity in provenance['inputs'].items():
    assert streamed_sha(ROOT/'work/parent-full-program/capture'/name)==identity['sha256']
assert json.loads((ROOT/'outputs/mac-m18-framing01/result01.json').read_text())['status']=='passed'
db=sqlite3.connect(DB.resolve().as_uri()+'?mode=ro',uri=True)
selected=json.loads(db.execute('SELECT value FROM metadata WHERE key="complete"').fetchone()[0])
p=52435875175126190479447740508185965837690552500527637822603658699938581184513
copy=selected['constant_copy'];assert copy==200692
indices=[0,1,2,3,177954,200767,200768,200769]
nodes=[]
for row in db.execute('SELECT id,op,lk,li,rk,ri,kind,terms,certificate FROM nodes WHERE id<8 ORDER BY id'):
    ordinal,op,lk,li,rk,ri,kind,terms,cert=row
    nodes.append(dict(id=ordinal,op=op,left=[lk,li],right=[rk,ri],kind=kind,
                      terms=json.loads(terms),certificate=json.loads(cert)))
assert len(nodes)==8
constants=[int(db.execute('SELECT value FROM constants WHERE id=?',(i,)).fetchone()[0],16) for i in range(3)]
assert constants[1:]==[p-1,1]
rows=[]
for index in indices:
    a,b,origin=db.execute('SELECT a,b,origin FROM rows WHERE id=?',(index,)).fetchone()
    outlined=lambda raw:[[copy if col==0 and index!=200769 else col,value] for col,value in json.loads(raw)]
    rows.append(dict(capture_index=index,a=outlined(a),b=outlined(b),origin=json.loads(origin)))
assertion=json.loads(db.execute('SELECT certificate FROM assertions WHERE id=0').fetchone()[0])
assert assertion==dict(assertion=0,left=[2,0],right=[1,7],constructor='squareLinear',rows=[177954])
inputs=[7,13,14]
mapping={(1,value):i for i,value in enumerate(inputs)}
mapping.update({(0,value):3+value for value in range(3)})
mapping.update({(2,value):6+value for value in range(8)})
def linear(terms):return '['+', '.join(f'({c}, {v})' for c,v in terms)+']'
def fin(i):return f'⟨{i}, by decide⟩'
def expression(kind,terms):return f'.{kind} {linear(terms)}'
expressions=[('linear',[[3+i,1]]) for i in inputs]+[('linear',[[0,c]]) for c in constants]
expressions += [(n['kind'],n['terms']) for n in nodes]
source=['.input '+str(i) for i in inputs]+['.constant '+str(c) for c in constants]
for n in nodes:
    ordinal=6+n['id']
    reference=lambda ref: f'⟨{mapping[tuple(ref)]}, by change {mapping[tuple(ref)]} < {ordinal}; decide⟩'
    source.append(f'.{n["op"]} {reference(n["left"])} {reference(n["right"])}')
data=dict(runtime_sha='844389ee069e1fb2e576708842d0b389b4d9a44a',source_identity=selected['source_identity'],
          data_gate_receipt_sha256=sha(ROOT/'outputs/mac-m18-framing01/result01.json'),
          arithmetic_nodes=nodes,constants=constants,assertion=assertion,rows=rows,
          leaf_inputs=inputs,source_mapping=[dict(kind=k,ordinal=o,local=i) for (k,o),i in mapping.items()],
          full_graph=False,full_row_instance=False)
data['provenance_receipt_sha256']=sha(OUT/'provenance-successor01.json')
data['pilot_output_scope']='local index13 is chosen pilot output, not captured runtime output'
data_index=1
while (OUT/f'pilot-data{data_index:02d}.json').exists():data_index+=1
(OUT/f'pilot-data{data_index:02d}.json').write_text(json.dumps(data,indent=2)+'\n')
text=['-- GENERATED by generate_pilot.py; change the generator, never this file.',
      'import ShielddSecurity.CompilerCompletion','import ShielddSecurity.CompilerCertificateTransport',
      'import ShielddSecurity.SourceGraphEvaluation','',
      'set_option maxHeartbeats 400000','set_option maxRecDepth 4096','',
      'namespace ShielddSecurity.TransferCompilerPilotData01','open Compiler CompilerCompletion',
      f'def p : Nat := {p}',f'def copy : Nat := {copy}',
      f'def coefficient : Int := {constants[0]}',
      'def inputTerms (i : Nat) : Linear := [(3+i,1)]',
      'def captureIndices : List Nat := '+str(indices),
      'def originalRows : List Row := ['+',\n  '.join('⟨'+linear(r['a'])+', '+linear(r['b'])+'⟩' for r in rows)+']',
      'def unoutlinedRows : List Row := unoutlineRows copy originalRows',
      'def node (index : Fin 14) : SourceNode index.val := match index with']
text += [f'  | ⟨{i}, _⟩ => {value}' for i,value in enumerate(source)]
text += ['  | ⟨n+14, h⟩ => False.elim (by omega)',
         'def expressions (index : Fin 14) : Expression := match index.val with']
text += [f'  | {i} => {expression(kind,terms)}' for i,(kind,terms) in enumerate(expressions)]
text += ['  | _ => .linear []',
         'theorem input_bound (index : Fin 14) (input : Nat) (h : node index = .input input) : input < 22735 := by',
         '  rcases index with ⟨n, hn⟩',
         '  have cases : '+ ' ∨ '.join(f'n = {i}' for i in range(14))+' := by omega',
         '  rcases cases with '+ ' | '.join('h'+str(i) for i in range(14)),
         '  all_goals subst n; simp [node] at h',
         '  all_goals omega',
         'def graph : SourceGraph 22735 14 := ⟨node, input_bound, [('+fin(6)+', '+fin(0)+')], ['+fin(13)+']⟩']
for i in range(14):
    kind,terms=expressions[i]
    text += [f'theorem certificate_{i:02d} : NodeCertificate p unoutlinedRows inputTerms',
             f'    (graph.prior expressions {fin(i)}) (graph.node {fin(i)}) (expressions {fin(i)}) := by']
    if i<3:
        proof=f'exact .input {inputs[i]} {linear(terms)} (by decide)'
    elif i<6:
        proof=f'exact .constant {constants[i-3]} {linear(terms)} (by decide)'
    else:
        n=nodes[i-6];cert=n['certificate'];left=mapping[tuple(n['left'])];right=mapping[tuple(n['right'])]
        x=linear(expressions[left][1]);y=linear(expressions[right][1]);out=linear(terms)
        common=f'{fin(left)} {fin(right)} {x} {y}'
        constructor=cert['constructor']
        if constructor=='add':proof=f'exact .add {common} {out} rfl rfl (by decide)'
        elif constructor.startswith('folded'):
            proof=f'exact .{constructor} {common} {out} {cert["coefficient"]} rfl rfl (by decide) (by decide)'
        elif constructor=='deferred':proof=f'exact .deferred {common} {out} rfl rfl (by decide) (by decide)'
        elif constructor=='square':proof=f'exact .square {common} {out} rfl rfl (by decide) (by decide)'
        elif constructor=='product':proof=f'exact .product {common} {out} {linear(cert["auxiliary"])} rfl rfl (by decide) (by decide)'
        else:raise ValueError(constructor)
    text.append('  '+proof)
text += ['theorem node_certificates (index : Fin 14) : NodeCertificate p unoutlinedRows inputTerms',
         '    (graph.prior expressions index) (graph.node index) (expressions index) := by',
         '  rcases index with ⟨n, hn⟩',
         '  have cases : '+ ' ∨ '.join(f'n = {i}' for i in range(14))+' := by omega',
         '  rcases cases with '+ ' | '.join('h'+str(i) for i in range(14))]
text += [f'  · subst n; exact certificate_{i:02d}' for i in range(14)]
text += ['theorem assertion_certificate : AssertionCertificate p unoutlinedRows',
         '    (expressions '+fin(6)+') (expressions '+fin(0)+') := by',
         '  exact .squareLinear [(10,1)] [(10,1)] (by decide)',
         'theorem assertion_certificates (assertion : Fin 14 × Fin 14)',
         '    (member : assertion ∈ graph.assertions) :',
         '    AssertionCertificate p unoutlinedRows (expressions assertion.1) (expressions assertion.2) := by',
         '  have equal : assertion = ('+fin(6)+', '+fin(0)+') := by simpa [graph] using member',
         '  subst assertion; exact assertion_certificate',
         'end ShielddSecurity.TransferCompilerPilotData01']
for theorem in [f'certificate_{i:02d}' for i in range(14)]+['input_bound','node_certificates','assertion_certificate','assertion_certificates']:
    name='ShielddSecurity.TransferCompilerPilotData01.'+theorem
    text += ['set_option pp.all true in','#check @'+name,'#print axioms '+name]
target=PROJECT/'ShielddSecurity/TransferCompilerPilotData01.lean'
