"""Generate checked production controls from maintained templates, atomically."""
import hashlib,json,os,re
from pathlib import Path
S=Path(__file__).resolve().parent;R=S.parents[1];O=R/'outputs/mac-poseidon-absorb02';P=S/'project/ShielddSecurity'
records=[]
for template,module in [('absorption-controls-data-template.lean.txt','TransferPoseidonAbsorb02ControlsData01'),('absorption-controls-template.lean.txt','TransferPoseidonAbsorb02Controls01'),('first-two-controls-data-template.lean.txt','TransferPoseidonFirstTwo02ControlsData01'),('first-two-controls-template.lean.txt','TransferPoseidonFirstTwo02Controls01')]:
 source=(S/template).read_text(); text=source
 names=re.findall(r'^theorem (\w+)',source,re.M)
 for name in reversed(names):
  start=re.search(r'^theorem '+name+r'\b',text,re.M).start()
  nxt=re.search(r'^(theorem|variable|end)\b',text[start+1:],re.M)
  at=start+1+nxt.start()
  text=text[:at]+f'set_option pp.all true in\n#check @ShielddSecurity.{module}.{name}\n#print axioms ShielddSecurity.{module}.{name}\n\n'+text[at:]
 text='-- GENERATED by generate_controls.py from '+template+'; edit the template.\n'+text
 b=text.encode();target=P/(module+'.lean')
 if target.exists() and target.read_bytes()!=b:
  old=target.read_bytes();hist=O/'source-history';hist.mkdir(exist_ok=True);(hist/(module+'-'+hashlib.sha256(old).hexdigest()+'.lean')).write_bytes(old)
 tmp=target.with_suffix('.tmp');tmp.write_bytes(b);os.replace(tmp,target)
 records.append(dict(module=module,sha256=hashlib.sha256(b).hexdigest(),bytes=len(b),template=template,template_sha256=hashlib.sha256(source.encode()).hexdigest(),audit_names=names))
idx=1
while (O/f'controls-generation{idx:02d}.json').exists():idx+=1
receipt=dict(generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),sources=records)
(O/f'controls-generation{idx:02d}.json').write_text(json.dumps(receipt,indent=2)+'\n');print(json.dumps(receipt))
