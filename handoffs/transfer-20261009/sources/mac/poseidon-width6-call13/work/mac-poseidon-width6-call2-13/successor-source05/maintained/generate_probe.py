"""Generate ONLY the two admitted Call13 probes from the frozen compact input."""
import argparse,hashlib,json,sys
from pathlib import Path
if not __debug__:raise RuntimeError('Python optimization unsupported')
S=Path(__file__).resolve().parent
sys.path.insert(0,str(S))
from validate_records import validate_node
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
assert sha(S/'validate_records.py')=='5c5f32ef5167b259b8ee66f1a825457b8dcbf647c6c2ce417778ef8f4423b20d'
parser=argparse.ArgumentParser()
parser.add_argument('--input',type=Path,required=True)
parser.add_argument('--parameters',type=Path,required=True)
parser.add_argument('--output-dir',type=Path,required=True)
parser.add_argument('--metadata-dir',type=Path,required=True)
args=parser.parse_args()
assert sha(args.input)=='5b675620e919dd51f9c35dd12ebb114dbb0d13493093909ad49000a718211a25'
c=json.loads(args.input.read_text());d=c['projection']
assert c['full_local_descriptor_sha256']=='d38816aadf8b9522d9627323516e3d2cf97717cc4cd0a04f9c5f9ca9873a5367'
assert d['runtime_sha']=='844389ee069e1fb2e576708842d0b389b4d9a44a'
assert sha(args.parameters)==d['parameter_sha256']=='84a51d11b64641fc3604b4cbedbe7cc82e91204b21d3bd62fb59462bbb4a5bb8'
assert json.loads(args.parameters.read_text())==d['parameters']
assert d['actual_input_columns']==[34,35,36,42,43]
assert len(d['prefix_scopes'])==2
rows={r['capture_index']:r for r in d['indexed_original_rows']}
assert len(rows)==417
constants={x['id']:x['value'] for x in c['prefix_allocated_constants']}
assert len(constants)==94
for scope in d['prefix_scopes']:
    ns={n['source_node']:n for n in scope['nodes']}
    for node in ns.values():
        validate_node(node)
        left,right=node['left'],node['right'];cert=node['certificate']
        for port in [left,right]:
            assert port[0] in [0,1,2]
            if port[0]==0:assert port[1] in constants
        if cert['constructor']=='foldedLeft':
            assert cert['coefficient']==constants[left[1]]
        if cert['constructor']=='foldedRight':
            assert cert['coefficient']==constants[right[1]]
        for index in cert['rows']:
            assert index in scope['phase']['row_indices'] and rows[index]['origin']['id']==node['source_node']

lc=lambda t:'['+', '.join(f'({col},{coeff})' for col,coeff in t)+']'
row=lambda v:'⟨'+lc(v['a'])+','+lc(v['b'])+'⟩'
audit=lambda m,n:f'\nset_option pp.all true in\n#check @ShielddSecurity.{m}.{n}\n#print axioms ShielddSecurity.{m}.{n}\n'
data_ns='TransferPoseidonCall13ProbeData01'
proof_ns='TransferPoseidonCall13R00Column1Probe01'
lines=['-- GENERATED by generate_probe.py; exact admitted Call13 prefix data only.',
       'import ShielddSecurity.PoseidonIndexedFolded02',
       'import ShielddSecurity.TransferPoseidonCall04Shared01',
       'import ShielddSecurity.CompilerOrder',
       'set_option autoImplicit false','set_option maxHeartbeats 900000','set_option maxRecDepth 8192',
       f'namespace ShielddSecurity.{data_ns}',
       'open Compiler CompilerCompletion Poseidon PoseidonIndexedFolded02 TransferPoseidonCall04Shared01']
for scope in d['prefix_scopes']:
    index=scope['round'];assert scope['block']==0 and index in [0,1]
    stem=f'R{index:02d}';phase=scope['phase'];ns={n['source_node']:n for n in scope['nodes']}
    indices=phase['row_indices']+[200769]
    mapping={i:j for j,i in enumerate(indices)}
    lines.append(f'def {stem}Rows : Array Row := Array.mk ['+',\n'.join(row(rows[i]) for i in indices)+']')
    for label in ['before','after_ark','after_sbox','after']:
        lines.extend([f'def {stem}{label} (column : Fin 6) : Linear := match column.val with']+
                     [f'  | {j} => {lc(t)}' for j,t in enumerate(phase['ports'][label])]+['  | _ => []'])
    hints=[]
    for column,ref in enumerate(phase['raw_ports']['after_sbox']):
        if ref[0]=='native':
            assert index==column==0
            coefficient=phase['raw_ports']['after_ark'][column][1]
            hints.append('.constant '+str(coefficient));continue
        product=ns[ref[1]];cert=product['certificate']
        assert cert['constructor']=='product' and product['right']==phase['raw_ports']['after_ark'][column]
        fourth=ns[product['left'][1]];square=ns[fourth['left'][1]]
        assert square['certificate']['constructor']==fourth['certificate']['constructor']=='square'
        assert square['left']==square['right']==product['right'] and fourth['left']==fourth['right']
        hints.append('.arithmetic ⟨'+', '.join([lc(square['expression']['terms']),lc(fourth['expression']['terms']),lc(cert['auxiliary'])]+
                    [str(mapping[x]) for x in [square['certificate']['rows'][0],fourth['certificate']['rows'][0],*cert['rows']]])+'⟩')
    lines.extend([f'def {stem}Hints (column : Fin 6) : FifthHint := match column.val with']+
                 [f'  | {j} => {v}' for j,v in enumerate(hints)]+['  | _ => .constant 0'])
scope=d['prefix_scopes'][0];phase=scope['phase'];ns={n['source_node']:n for n in scope['nodes']}
product=ns[phase['raw_ports']['after_sbox'][1][1]];fourth=ns[product['left'][1]];square=ns[fourth['left'][1]]
assert [square['source_node'],fourth['source_node'],product['source_node']]==[16636,16637,16638]
assert square['expression']['terms']==[[24308,1]] and fourth['expression']['terms']==[[24309,1]]
assert product['expression']['terms']==[[24310,1]] and product['certificate']['auxiliary']==[[24311,1]]
indices=[square['certificate']['rows'][0],fourth['certificate']['rows'][0],*product['certificate']['rows'],200769]
assert indices==[1570,1571,1572,1573,200769]
shifted=phase['ports']['after_ark'][1]
lines += [f'def columnRows : Array Row := Array.mk ['+',\n'.join(row(rows[i]) for i in indices)+']',
          'def columnCaptureIndices : Array Nat := #[1570,1571,1572,1573,200769]',
          'def columnSteps : List Step := ['+
          f'.square {lc(shifted)} [] 24308, .square [(24308,1)] [] 24309, '+
          f'.product [(24309,1)] {lc(shifted)} [] 24310 24311, copyStep]',
          'def columnEmitted : Array Row := (emitted columnSteps).toArray',
          'def columnMapping : Array Nat := #[0,1,2,3,4]']
for name,body in [
 ('table_counts','R00Rows.size=21 ∧ R01Rows.size=25 ∧ columnRows.size=5 ∧ columnSteps.length=4'),
 ('column_order_checked','CompilerOrder.checkOrder [0,copy] [] columnSteps=true'),
 ('column_coverage_checked','CompilerIndexed01.checkOriginalCoverage p copy columnRows columnEmitted columnMapping=true'),
 ('actual_copy_checked','CompilerIndexed01.checkRowAt p columnRows 4 ⟨[(0,1),(copy,-1)],[]⟩=true')]:
    lines.append(f'theorem {name} : {body} := by decide +kernel')
    lines.append(audit(data_ns,name))
lines.append(f'end ShielddSecurity.{data_ns}')
data='\n'.join(lines)+'\n'

proof=f'''-- GENERATED by generate_probe.py; ONLY round0 column1 and its local constructor.
import ShielddSecurity.{data_ns}
set_option autoImplicit false
set_option maxHeartbeats 900000
set_option maxRecDepth 8192
namespace ShielddSecurity.{proof_ns}
open Compiler CompilerCompletion Poseidon PoseidonIndexedFolded02 TransferPoseidonCall04Shared01 {data_ns}
'''
def theorem(name,body):return body+audit(proof_ns,name)
proof+=theorem('column1_checked','''theorem column1_checked : checkColumn p copy R00Rows parameters 0
    R00before R00after_ark R00after_sbox R00Hints 1=true := by decide +kernel
''')
proof+=theorem('fifth_checked','''theorem fifth_checked : checkFifth p copy columnRows (R00after_ark 1)
    (R00after_sbox 1) (R00Hints 1)=true := by decide +kernel
''')
proof+=theorem('fifth_certificate','''theorem fifth_certificate : FifthCertificate p (unoutlineRows copy columnRows.toList)
    (R00after_ark 1) (R00after_sbox 1) :=
  checkFifth_sound p copy columnRows _ _ (R00Hints 1) fifth_checked
''')
proof+=theorem('topological','''theorem topological : Topological [0,copy] [] columnSteps :=
  CompilerOrder.checked_order [0,copy] [] columnSteps column_order_checked
''')
proof+='variable {F : Type} [Field F]\ndef completed (base : Nat → F) : Nat → F := run base columnSteps\n'
proof+=theorem('legal','''theorem legal (base : Nat → F) : Legal base columnSteps := by
  simp [columnSteps,copyStep,Legal,Step.Legal]
''')
proof+=theorem('constructed_rows','''theorem constructed_rows [CharP F p] (base : Nat → F) (linked : base copy=base 0) :
    Satisfies (completed base) columnRows.toList := by
  have coverage := CompilerIndexed01.checkOriginalCoverage_sound p copy columnRows columnEmitted columnMapping column_coverage_checked
  exact (original_rows_complete base columnSteps [0,copy] columnRows.toList copy
    topological (legal base) (by simp) (by simp) linked coverage).1
''')
proof+=theorem('outside_preserved','''theorem outside_preserved (base : Nat → F) (column : Nat)
    (outside : column<24308 ∨ 24311<column) : completed base column=base column := by
  apply PoseidonCompletion.run_outside base columnSteps column
  have excluded : column≠24308 ∧ column≠24309 ∧ column≠24310 ∧ column≠24311 := by omega
  simpa [PoseidonCompletion.writes,columnSteps,Step.writes,copyStep] using excluded
''')
proof+=theorem('original_inputs_preserved','''theorem original_inputs_preserved (base : Nat → F) (input : Nat) (bound : input<22735) :
    completed base (3+input)=base (3+input) := outside_preserved base (3+input) (Or.inl (by omega))
''')
proof+=theorem('copy_preserved','''theorem copy_preserved (base : Nat → F) : completed base copy=base copy :=
  outside_preserved base copy (Or.inr (by decide))
''')
proof+=theorem('arbitrary_fifth_value','''theorem arbitrary_fifth_value [CharP F p] (rho : Nat → F) (one : rho 0=1)
    (four : (4:F)≠0) (satisfied : Satisfies rho columnRows.toList) :
    eval rho (R00after_sbox 1)=eval rho (R00after_ark 1)^5 := by
  exact fifth_certificate_sound rho (unoutlineRows copy columnRows.toList) _ _ one four
    (unoutline_rows_sound rho copy columnRows.toList satisfied
      (CompilerIndexed01.checkRowAt_sound p columnRows 4 _ actual_copy_checked)) fifth_certificate
''')
proof+=f'end ShielddSecurity.{proof_ns}\n'
args.output_dir.mkdir(parents=True,exist_ok=True);args.metadata_dir.mkdir(parents=True,exist_ok=True)
sources={}
for name,content in [(data_ns,data),(proof_ns,proof)]:
    path=args.output_dir/(name+'.lean')
    if path.exists():
        historical=args.metadata_dir/'source-history'/sha(path)/path.name
        historical.parent.mkdir(parents=True,exist_ok=True)
        assert not historical.exists() or historical.read_bytes()==path.read_bytes()
        historical.write_bytes(path.read_bytes())
    path.write_text(content);sources[name]={'sha256':sha(path),'bytes':path.stat().st_size}
assert sum(x['bytes'] for x in sources.values())<=262144
metadata={'generator_sha256':sha(Path(__file__)),'validator_sha256':sha(S/'validate_records.py'),
          'input_sha256':sha(args.input),'parameter_sha256':sha(args.parameters),
          'sources':sources,'scope':'two admitted probes only; R0column1 fifth certificate/local5row constructor, not full round/call'}
index=1
while (args.metadata_dir/f'probe-generation{index:02d}.json').exists():index+=1
(args.metadata_dir/f'probe-generation{index:02d}.json').write_text(json.dumps(metadata,indent=2)+'\n')
print(json.dumps(metadata))
